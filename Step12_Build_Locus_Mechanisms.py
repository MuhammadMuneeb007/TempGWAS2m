def prepare_variant_table(x: pd.DataFrame, accession: str, source: str) -> pd.DataFrame:
    if x.empty:
        return x
    x = x.copy()
    if "STUDY_ACCESSION" not in x.columns:
        x["STUDY_ACCESSION"] = accession
    x["STUDY_ACCESSION"] = accession
    x["VARIANT_SOURCE_TABLE"] = source
    if "LOCUS_ID" not in x.columns:
        x["LOCUS_ID"] = ""
    x["VARIANT_KEY"] = x.apply(canonical_variant_from_row, axis=1)
    if "PIP" in x.columns:
        x["PIP"] = pd.to_numeric(x["PIP"], errors="coerce")
    if "SPLICEAI_MAX_DS" in x.columns:
        x["SPLICEAI_MAX_DS"] = pd.to_numeric(x["SPLICEAI_MAX_DS"], errors="coerce")
    if "PANGOLIN_MAX_ABS" in x.columns:
        x["PANGOLIN_MAX_ABS"] = pd.to_numeric(x["PANGOLIN_MAX_ABS"], errors="coerce")
    return x


def load_best_variant_table(files: dict[str, Path | None], accession: str) -> tuple[pd.DataFrame, str]:
    # Richest downstream table first. Step10's integrated table carries Step09,
    # which carries Step08, which carries Step07/VEP + fine-mapping evidence.
    choices = [
        ("STEP10_INTEGRATED", files["S10_VARIANTS"]),
        ("STEP09_SPLICEAI", files["S09_VARIANTS"]),
        ("STEP08_QTL", files["S08_VARIANTS"]),
        ("STEP07_VEP", files["S07_VARIANTS"]),
        ("STEP06_FINEMAP", files["S06_VARIANTS"]),
    ]
    for label, path in choices:
        x = read_table(path)
        if not x.empty:
            return prepare_variant_table(x, accession, label), label
    return pd.DataFrame(), "MISSING"


