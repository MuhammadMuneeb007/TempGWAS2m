def parse_first_lead_position(value) -> float:
    vals = re.findall(r"\d+", str(value))
    return float(vals[0]) if vals else np.nan


def reciprocal_overlap(a1: float, a2: float, b1: float, b2: float) -> float:
    inter = max(0.0, min(a2, b2) - max(a1, b1) + 1.0)
    if inter <= 0:
        return 0.0
    la = max(1.0, a2 - a1 + 1.0)
    lb = max(1.0, b2 - b1 + 1.0)
    return min(inter / la, inter / lb)


def build_consensus_loci(locus_summary: pd.DataFrame,
                         min_recip_overlap: float,
                         lead_distance_bp: int) -> pd.DataFrame:
    if locus_summary.empty:
        return pd.DataFrame()
    req = {"CHR", "LOCUS_START", "LOCUS_END"}
    if not req.issubset(locus_summary.columns):
        return pd.DataFrame()

    x = locus_summary.copy()
    x["LOCUS_START"] = pd.to_numeric(x["LOCUS_START"], errors="coerce")
    x["LOCUS_END"] = pd.to_numeric(x["LOCUS_END"], errors="coerce")
    x["CHR"] = x["CHR"].map(canonical_chr)
    x["_LEAD"] = x.get("LEAD_POSITIONS", pd.Series("", index=x.index)).map(parse_first_lead_position)
    x = x.dropna(subset=["LOCUS_START", "LOCUS_END"])

    # Union-find over loci meeting either reciprocal-overlap or lead-distance rule.
    n = len(x)
    parent = list(range(n))

    def find(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i

    def union(i, j):
        ri, rj = find(i), find(j)
        if ri != rj:
            parent[rj] = ri

    records = x.reset_index(drop=True)
    for chrom, idxs in records.groupby("CHR").groups.items():
        idxs = list(idxs)
        for ii, i in enumerate(idxs):
            a = records.loc[i]
            for j in idxs[ii + 1:]:
                b = records.loc[j]
                if float(b["LOCUS_START"]) > float(a["LOCUS_END"]) + lead_distance_bp:
                    # sortedness is not guaranteed globally, so do not break.
                    pass
                ro = reciprocal_overlap(
                    float(a["LOCUS_START"]), float(a["LOCUS_END"]),
                    float(b["LOCUS_START"]), float(b["LOCUS_END"]),
                )
                lead_close = (
                    pd.notna(a["_LEAD"]) and pd.notna(b["_LEAD"])
                    and abs(float(a["_LEAD"]) - float(b["_LEAD"])) <= lead_distance_bp
                )
                if ro >= min_recip_overlap or lead_close:
                    union(i, j)

    groups = defaultdict(list)
    for i in range(n):
        groups[find(i)].append(i)

    rows = []
    ordered = sorted(groups.values(), key=lambda members: (
        records.loc[members[0], "CHR"],
        float(records.loc[members, "LOCUS_START"].min()),
    ))
    for number, members in enumerate(ordered, start=1):
        g = records.loc[members].copy()
        top_genes = [x for x in g.get("TOP_GENE", pd.Series("", index=g.index)).astype(str) if x]
        mechanisms = join_unique(g.get("LOCUS_MECHANISM", pd.Series("", index=g.index)))
        rows.append({
            "CONSENSUS_LOCUS_ID": f"CL{number:04d}",
            "CHR": str(g["CHR"].iloc[0]),
            "CONSENSUS_START": int(g["LOCUS_START"].min()),
            "CONSENSUS_END": int(g["LOCUS_END"].max()),
            "N_STUDY_LOCI": len(g),
            "N_STUDIES": g["STUDY_ACCESSION"].nunique(),
            "STUDY_LOCI": ";".join(
                f"{r.STUDY_ACCESSION}:{r.LOCUS_ID}" for r in g.itertuples(index=False)
            ),
            "TOP_GENES": ";".join(dict.fromkeys(top_genes)),
            "MECHANISMS": mechanisms,
            "BEST_TIER": min(
                [TIER_RANK.get(str(v), 99) for v in g.get("TOP_GENE_TIER", pd.Series("", index=g.index))],
                default=99,
            ),
            "INTERPRETATION_STATUSES": join_unique(
                g.get("LOCUS_INTERPRETATION_STATUS", pd.Series("", index=g.index))
            ),
        })
    out = pd.DataFrame(rows)
    if not out.empty:
        inv = {v: k for k, v in TIER_RANK.items()}
        out["BEST_TIER"] = out["BEST_TIER"].map(inv).fillna("UNRESOLVED")
    return out


def build_pathway_input(ranked: pd.DataFrame, max_tier_rank: int) -> pd.DataFrame:
    if ranked.empty:
        return pd.DataFrame()
    x = ranked[ranked["TIER_RANK"] <= max_tier_rank].copy()
    x = x[x["GENE_DISPLAY"].astype(str).str.strip() != ""]
    if x.empty:
        return pd.DataFrame()

    rows = []
    for gene, g in x.groupby("GENE_DISPLAY", sort=False):
        pp4 = pd.to_numeric(g.get("MAX_PP4", pd.Series(np.nan, index=g.index)), errors="coerce")
        pip = pd.to_numeric(g.get("MAX_PIP", pd.Series(np.nan, index=g.index)), errors="coerce")
        rows.append({
            "GENE": gene,
            "GENE_ID": str(first_nonempty(g.get("GENE_ID", pd.Series("", index=g.index)).tolist())),
            "BEST_TIER": g.sort_values("TIER_RANK")["EVIDENCE_TIER"].iloc[0],
            "N_STUDIES": g["STUDY_ACCESSION"].nunique(),
            "N_STUDY_LOCI": len(g[["STUDY_ACCESSION", "LOCUS_ID"]].drop_duplicates()),
            "STUDY_LOCI": ";".join(
                f"{r.STUDY_ACCESSION}:{r.LOCUS_ID}" for r in g[["STUDY_ACCESSION", "LOCUS_ID"]].drop_duplicates().itertuples(index=False)
            ),
            "MAX_PP4": pp4.max() if pp4.notna().any() else np.nan,
            "MAX_PIP": pip.max() if pip.notna().any() else np.nan,
            "MECHANISMS": join_unique(g["DOMINANT_MECHANISM"]),
            "STRONG_QTL_TYPES": join_unique(g["STRONG_QTL_TYPES"]),
            "SUGGESTIVE_QTL_TYPES": join_unique(g["SUGGESTIVE_QTL_TYPES"]),
        })
    out = pd.DataFrame(rows)
    if not out.empty:
        out["_TIER"] = out["BEST_TIER"].map(TIER_RANK).fillna(99)
        out = out.sort_values(
            ["_TIER", "N_STUDY_LOCI", "MAX_PP4", "MAX_PIP", "GENE"],
            ascending=[True, False, False, False, True],
            kind="stable",
        ).drop(columns="_TIER")
    return out


