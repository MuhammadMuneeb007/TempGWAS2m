def build_ensembl_symbol_maps(variants: pd.DataFrame) -> tuple[dict[str, str], dict[str, str]]:
    ens_to_symbol: dict[str, str] = {}
    symbol_to_ens: dict[str, str] = {}
    if variants.empty:
        return ens_to_symbol, symbol_to_ens
    for _, row in variants.iterrows():
        ens = gene_base(row.get("Gene", ""))
        symbol = str(row.get("SYMBOL", "")).strip()
        if ens.startswith("ENSG") and symbol:
            ens_to_symbol.setdefault(ens, symbol)
            symbol_to_ens.setdefault(symbol.upper(), ens)
    return ens_to_symbol, symbol_to_ens


def canonical_gene_key(token: str, symbol_to_ens: dict[str, str]) -> tuple[str, str, str]:
    token = str(token).strip()
    if not token:
        return "", "", ""
    base = gene_base(token)
    if base.startswith("ENSG"):
        return base, base, ""
    symbol = token
    ens = symbol_to_ens.get(symbol.upper(), "")
    if ens:
        return ens, ens, symbol
    return symbol.upper(), "", symbol


def variant_gene_links(variants: pd.DataFrame) -> pd.DataFrame:
    if variants.empty:
        return pd.DataFrame()

    ens_to_symbol, symbol_to_ens = build_ensembl_symbol_maps(variants)
    rows = []

    for _, row in variants.iterrows():
        base_info = {
            "STUDY_ACCESSION": row.get("STUDY_ACCESSION", ""),
            "LOCUS_ID": row.get("LOCUS_ID", ""),
            "VARIANT_KEY": row.get("VARIANT_KEY", ""),
            "REFERENCE_ID": row.get("REFERENCE_ID", row.get("SNPID", row.get("rsID", ""))),
            "PIP": row.get("PIP", np.nan),
            "IN_95_CREDIBLE_SET": boolish(
                row.get("IN_95_CREDIBLE_SET", row.get("SELECTED_CREDIBLE_SET", False))
            ),
            "FUNCTIONAL_CATEGORY": str(row.get("FUNCTIONAL_CATEGORY", "")).upper(),
            "IMPACT": str(row.get("IMPACT", "")).upper(),
            "CONSEQUENCE": row.get("Consequence", row.get("ALL_CONSEQUENCES", "")),
            "SPLICEAI_MAX_DS": row.get("SPLICEAI_MAX_DS", np.nan),
            "PANGOLIN_MAX_ABS": row.get("PANGOLIN_MAX_ABS", np.nan),
            "PANGOLIN_TOP_5PCT": boolish(row.get("PANGOLIN_TOP_5PCT", False)),
            "N_SPLICE_EVIDENCE_SOURCES": row.get("N_SPLICE_EVIDENCE_SOURCES", 0),
            "SPLICE_EVIDENCE_CLASS": row.get("SPLICE_EVIDENCE_CLASS", ""),
        }

        candidates: list[tuple[str, str]] = []

        # Direct VEP transcript-level mapping is the cleanest annotation link.
        direct_ens = gene_base(row.get("Gene", ""))
        direct_symbol = str(row.get("SYMBOL", "")).strip()
        if direct_ens or direct_symbol:
            token = direct_ens if direct_ens else direct_symbol
            candidates.append((token, "VEP"))
            if direct_ens.startswith("ENSG") and direct_symbol:
                ens_to_symbol.setdefault(direct_ens, direct_symbol)
                symbol_to_ens.setdefault(direct_symbol.upper(), direct_ens)

        for col, source in [
            ("ALL_SYMBOLS", "VEP_ALL_SYMBOLS"),
            ("SPLICEAI_GENE", "SPLICEAI"),
            ("SPLICEAI_ALL_GENES", "SPLICEAI"),
            ("PANGOLIN_GENE", "PANGOLIN"),
            ("PANGOLIN_ALL_GENES", "PANGOLIN"),
        ]:
            if col in row.index:
                for token in split_tokens(row.get(col, "")):
                    candidates.append((token, source))

        seen = set()
        for token, source in candidates:
            key, ens, symbol = canonical_gene_key(token, symbol_to_ens)
            if not key:
                continue
            if not symbol and ens:
                symbol = ens_to_symbol.get(ens, "")
            marker = (key, source)
            if marker in seen:
                continue
            seen.add(marker)
            rows.append({
                **base_info,
                "GENE_KEY": key,
                "GENE_ID": ens,
                "GENE_SYMBOL": symbol,
                "GENE_SOURCE": source,
            })

    return pd.DataFrame(rows)


def best_text_by_rank(group: pd.DataFrame, column: str, rank_map: dict[str, int]) -> str:
    if column not in group.columns or group.empty:
        return ""
    vals = group[column].fillna("").astype(str).str.upper()
    if vals.empty:
        return ""
    ranks = vals.map(rank_map).fillna(99)
    if ranks.empty:
        return ""
    idx = ranks.idxmin()
    return str(group.loc[idx, column])


def aggregate_variant_gene_evidence(links: pd.DataFrame) -> pd.DataFrame:
    if links.empty:
        return pd.DataFrame()
    rows = []
    for (study, locus, gene_key), g in links.groupby(
        ["STUDY_ACCESSION", "LOCUS_ID", "GENE_KEY"], dropna=False, sort=False
    ):
        pips = pd.to_numeric(g["PIP"], errors="coerce")
        sai = pd.to_numeric(g["SPLICEAI_MAX_DS"], errors="coerce")
        pang = pd.to_numeric(g["PANGOLIN_MAX_ABS"], errors="coerce")
        nsplice = pd.to_numeric(g["N_SPLICE_EVIDENCE_SOURCES"], errors="coerce")
        top_pip = pips.max() if pips.notna().any() else np.nan
        if pips.notna().any():
            top_idx = pips.idxmax()
            best_variant = str(g.loc[top_idx, "VARIANT_KEY"])
            best_reference_id = str(g.loc[top_idx, "REFERENCE_ID"])
        else:
            best_variant = str(first_nonempty(g["VARIANT_KEY"].tolist()))
            best_reference_id = str(first_nonempty(g["REFERENCE_ID"].tolist()))

        rows.append({
            "STUDY_ACCESSION": study,
            "LOCUS_ID": locus,
            "GENE_KEY": gene_key,
            "GENE_ID": str(first_nonempty(g["GENE_ID"].tolist())),
            "GENE_SYMBOL": str(first_nonempty(g["GENE_SYMBOL"].tolist())),
            "VARIANT_GENE_SOURCES": join_unique(g["GENE_SOURCE"]),
            "N_GENE_LINKED_VARIANTS": int(g["VARIANT_KEY"].replace("", np.nan).nunique()),
            "MAX_PIP": top_pip,
            "N_95CS_GENE_VARIANTS": int(bool_series(g["IN_95_CREDIBLE_SET"]).sum()),
            "BEST_VARIANT": best_variant,
            "BEST_REFERENCE_ID": best_reference_id,
            "BEST_FUNCTIONAL_CATEGORY": best_text_by_rank(
                g, "FUNCTIONAL_CATEGORY", FUNCTIONAL_CATEGORY_RANK
            ),
            "BEST_IMPACT": best_text_by_rank(g, "IMPACT", IMPACT_RANK),
            "CONSEQUENCES": join_unique(g["CONSEQUENCE"]),
            "MAX_SPLICEAI_DS": sai.max() if sai.notna().any() else np.nan,
            "MAX_PANGOLIN_ABS": pang.max() if pang.notna().any() else np.nan,
            "ANY_PANGOLIN_TOP5": bool(bool_series(g["PANGOLIN_TOP_5PCT"]).any()),
            "MAX_SPLICE_EVIDENCE_SOURCES": int(nsplice.max()) if nsplice.notna().any() else 0,
            "SPLICE_EVIDENCE_CLASSES": join_unique(g["SPLICE_EVIDENCE_CLASS"]),
        })
    return pd.DataFrame(rows)


