def discover_studies(paths: dict[str, Path], study: str | None) -> list[str]:
    """Return only studies selected by strict Step11.

    Step12 runs after Step11, therefore coloc_manifest.tsv defines the
    authoritative phenotype/study/locus universe. Historical Step06-Step10
    directories must not re-introduce studies excluded before formal coloc.
    """
    manifest = paths["S11"] / "coloc_manifest.tsv"
    studies = set()

    if manifest.exists() and manifest.stat().st_size > 0:
        try:
            m = pd.read_csv(
                manifest,
                sep="\t",
                dtype=str,
                low_memory=False,
            )
        except pd.errors.EmptyDataError:
            m = pd.DataFrame()

        if not m.empty and "STUDY_ACCESSION" in m.columns:
            studies = {
                str(x).strip()
                for x in m["STUDY_ACCESSION"].dropna()
                if re.fullmatch(r"GCST\d+", str(x).strip())
            }

    # Legacy fallback: only genuine Step11 study output directories.
    if not studies and paths["S11"].exists():
        for child in paths["S11"].glob("GCST*"):
            if (
                child.is_dir()
                and re.fullmatch(r"GCST\d+", child.name)
                and (child / "loci").exists()
            ):
                studies.add(child.name)

    if study:
        requested = str(study).strip()
        studies = {x for x in studies if x == requested}

    return sorted(studies)


