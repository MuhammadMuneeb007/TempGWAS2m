def normalize_locus_definitions(loci: pd.DataFrame, accession: str) -> pd.DataFrame:
    if loci.empty:
        return loci
    x = loci.copy()
    if "STUDY_ACCESSION" not in x.columns:
        x["STUDY_ACCESSION"] = accession
    x["STUDY_ACCESSION"] = accession
    for col in ["LOCUS_START", "LOCUS_END"]:
        if col in x.columns:
            x[col] = pd.to_numeric(x[col], errors="coerce")
    if "CHR" in x.columns:
        x["CHR"] = x["CHR"].map(canonical_chr)
    return x


def qtl_wide_for_locus(locus_qtl: pd.DataFrame) -> pd.DataFrame:
    if locus_qtl.empty:
        return pd.DataFrame()
    rows = []
    for (study, locus), g in locus_qtl.groupby(["STUDY_ACCESSION", "LOCUS_ID"], sort=False):
        row = {"STUDY_ACCESSION": study, "LOCUS_ID": locus}
        for _, q in g.iterrows():
            qtype = re.sub(r"[^A-Za-z0-9]+", "_", str(q["QTL_TYPE"])).upper().strip("_")
            row[f"BEST_{qtype}_PP4"] = q.get("MAX_PP_H4", np.nan)
            row[f"BEST_{qtype}_PP3"] = q.get("MAX_PP_H3", np.nan)
            row[f"BEST_{qtype}_GENE"] = q.get("BEST_GENE", "")
            row[f"BEST_{qtype}_GENE_ID"] = q.get("BEST_GENE_ID", "")
            row[f"BEST_{qtype}_TISSUE"] = q.get("BEST_TISSUE", "")
            row[f"BEST_{qtype}_TRAIT"] = q.get("BEST_TRAIT", "")
            row[f"N_{qtype}_TESTED"] = q.get("N_FORMALLY_TESTED", 0)
            row[f"N_{qtype}_STRONG"] = q.get("N_STRONG", 0)
            row[f"N_{qtype}_SUGGESTIVE"] = q.get("N_SUGGESTIVE", 0)
            row[f"N_{qtype}_PRIOR_ROBUST"] = q.get("N_PRIOR_ROBUST_STRONG", 0)
        rows.append(row)
    return pd.DataFrame(rows)


def variant_locus_metrics(variants: pd.DataFrame) -> pd.DataFrame:
    if variants.empty:
        return pd.DataFrame()
    rows = []
    for (study, locus), g in variants.groupby(["STUDY_ACCESSION", "LOCUS_ID"], dropna=False, sort=False):
        pip = pd.to_numeric(g.get("PIP", pd.Series(np.nan, index=g.index)), errors="coerce")
        sai = pd.to_numeric(g.get("SPLICEAI_MAX_DS", pd.Series(np.nan, index=g.index)), errors="coerce")
        pang = pd.to_numeric(g.get("PANGOLIN_MAX_ABS", pd.Series(np.nan, index=g.index)), errors="coerce")
        top_variant = ""
        top_reference = ""
        top_category = ""
        top_impact = ""
        if pip.notna().any():
            idx = pip.idxmax()
            top_variant = str(g.loc[idx, "VARIANT_KEY"])
            top_reference = str(g.loc[idx].get("REFERENCE_ID", ""))
            top_category = str(g.loc[idx].get("FUNCTIONAL_CATEGORY", ""))
            top_impact = str(g.loc[idx].get("IMPACT", ""))
        rows.append({
            "STUDY_ACCESSION": study,
            "LOCUS_ID": locus,
            "N_VARIANTS_IN_MASTER": int(g["VARIANT_KEY"].replace("", np.nan).nunique()),
            "MAX_LOCUS_PIP": pip.max() if pip.notna().any() else np.nan,
            "TOP_PIP_VARIANT": top_variant,
            "TOP_PIP_REFERENCE_ID": top_reference,
            "TOP_PIP_FUNCTIONAL_CATEGORY": top_category,
            "TOP_PIP_IMPACT": top_impact,
            "MAX_LOCUS_SPLICEAI": sai.max() if sai.notna().any() else np.nan,
            "MAX_LOCUS_PANGOLIN": pang.max() if pang.notna().any() else np.nan,
        })
    return pd.DataFrame(rows)


def build_locus_summary(loci_all: pd.DataFrame, ranked: pd.DataFrame,
                        locus_qtl: pd.DataFrame, variants: pd.DataFrame,
                        step11_status: pd.DataFrame) -> pd.DataFrame:
    base = loci_all.copy()
    if base.empty:
        return pd.DataFrame()

    top_rows = []
    if not ranked.empty:
        for (study, locus), g in ranked.groupby(["STUDY_ACCESSION", "LOCUS_ID"], sort=False):
            g = g.sort_values("GENE_RANK")
            top = g.iloc[0]
            top3 = g.head(3)
            top_rows.append({
                "STUDY_ACCESSION": study,
                "LOCUS_ID": locus,
                "N_CANDIDATE_GENES": len(g),
                "TOP_GENE": top.get("GENE_DISPLAY", ""),
                "TOP_GENE_ID": top.get("GENE_ID", ""),
                "TOP_GENE_TIER": top.get("EVIDENCE_TIER", ""),
                "TOP_GENE_MECHANISM": top.get("DOMINANT_MECHANISM", ""),
                "TOP_GENE_REASON": top.get("RANKING_REASON", ""),
                "TOP_GENE_MAX_PIP": top.get("MAX_PIP", np.nan),
                "TOP_GENE_MAX_PP4": top.get("MAX_PP4", np.nan),
                "TOP3_GENES": ";".join(top3["GENE_DISPLAY"].astype(str).tolist()),
            })
    top_df = pd.DataFrame(top_rows)

    qwide = qtl_wide_for_locus(locus_qtl)
    vmetrics = variant_locus_metrics(variants)

    x = base.copy()
    for other in [top_df, qwide, vmetrics, step11_status]:
        if other is not None and not other.empty:
            keys = ["STUDY_ACCESSION", "LOCUS_ID"]
            keep = [c for c in other.columns if c not in x.columns or c in keys]
            x = x.merge(other[keep], on=keys, how="left")

    def classify(row: pd.Series) -> tuple[str, str]:
        step11 = str(row.get("STATUS", ""))
        top_gene = str(row.get("TOP_GENE", "")).strip()
        tier = str(row.get("TOP_GENE_TIER", ""))
        ca_pp4 = row.get("BEST_CAQTL_PP4", np.nan)
        ca_gene = str(row.get("BEST_CAQTL_GENE", "")).strip()
        strong_ca = pd.notna(ca_pp4) and float(ca_pp4) >= DEFAULT_STRONG_PP4
        n_tested = pd.to_numeric(pd.Series([row.get("N_TESTED", np.nan)]), errors="coerce").iloc[0]
        n_resource_errors = pd.to_numeric(pd.Series([row.get("N_RESOURCE_ERRORS", np.nan)]), errors="coerce").iloc[0]
        n_resource_unavailable = pd.to_numeric(pd.Series([row.get("N_RESOURCE_UNAVAILABLE", np.nan)]), errors="coerce").iloc[0]

        if step11 in {"FAILED", "NOT_TESTED_RESOURCE_UNAVAILABLE", "TIME_BUDGET_EXCEEDED"}:
            return "NOT_FULLY_INTERPRETABLE", f"STEP11_{step11}"
        if (
            (pd.isna(n_tested) or float(n_tested) == 0.0)
            and (
                (pd.notna(n_resource_errors) and float(n_resource_errors) > 0.0)
                or (pd.notna(n_resource_unavailable) and float(n_resource_unavailable) > 0.0)
            )
        ):
            return "NOT_FULLY_INTERPRETABLE", "STEP11_RESOURCE_FAILURE_WITHOUT_FORMAL_TEST"
        if top_gene and tier == "TIER1_HIGH":
            return "INTERPRETED_HIGH", str(row.get("TOP_GENE_MECHANISM", ""))
        if top_gene and tier == "TIER2_MODERATE":
            return "INTERPRETED_MODERATE", str(row.get("TOP_GENE_MECHANISM", ""))
        if top_gene:
            return "INTERPRETED_SUPPORTING", str(row.get("TOP_GENE_MECHANISM", ""))
        if strong_ca and not ca_gene:
            return "GENE_UNRESOLVED_REGULATORY", "CHROMATIN_REGULATION_WITHOUT_TARGET_GENE"
        return "UNRESOLVED", "NO_DEFENSIBLE_GENE_OR_MECHANISM"

    classes = x.apply(classify, axis=1, result_type="expand")
    classes.columns = ["LOCUS_INTERPRETATION_STATUS", "LOCUS_MECHANISM"]
    x = pd.concat([x, classes], axis=1)

    preferred = [
        "STUDY_ACCESSION", "LOCUS_ID", "CHR", "LOCUS_START", "LOCUS_END",
        "LEAD_IDS", "LEAD_POSITIONS", "MIN_LEAD_P",
        "LOCUS_INTERPRETATION_STATUS", "TOP_GENE", "TOP_GENE_ID",
        "TOP_GENE_TIER", "TOP_GENE_MECHANISM", "TOP_GENE_REASON", "TOP3_GENES",
        "TOP_GENE_MAX_PIP", "TOP_GENE_MAX_PP4",
        "TOP_PIP_VARIANT", "TOP_PIP_REFERENCE_ID", "TOP_PIP_FUNCTIONAL_CATEGORY",
        "MAX_LOCUS_PIP", "MAX_LOCUS_SPLICEAI", "MAX_LOCUS_PANGOLIN",
        "BEST_EQTL_PP4", "BEST_EQTL_GENE", "BEST_EQTL_TISSUE",
        "BEST_SQTL_PP4", "BEST_SQTL_GENE", "BEST_SQTL_TISSUE",
        "BEST_PQTL_PP4", "BEST_PQTL_GENE", "BEST_PQTL_TISSUE",
        "BEST_CAQTL_PP4", "BEST_CAQTL_GENE", "BEST_CAQTL_TISSUE",
        "LOCUS_MECHANISM", "STATUS", "N_TESTED", "N_RESOURCE_ERRORS",
        "N_RESOURCE_UNAVAILABLE",
    ]
    front = [c for c in preferred if c in x.columns]
    rest = [c for c in x.columns if c not in front]
    return x[front + rest]


