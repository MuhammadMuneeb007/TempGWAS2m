def map_coloc_gene(row: pd.Series, ens_to_symbol: dict[str, str],
                   symbol_to_ens: dict[str, str]) -> tuple[str, str, str]:
    raw = str(row.get("GENE_ID", "")).strip()
    if not raw:
        # Some QTL sources place an Ensembl gene in the molecular trait identifier.
        trait = str(row.get("MOLECULAR_TRAIT_ID", ""))
        m = re.search(r"(ENSG\d+)", trait, re.I)
        if m:
            raw = m.group(1)
    if not raw:
        return "", "", ""
    base = gene_base(raw)
    if base.startswith("ENSG"):
        return base, base, ens_to_symbol.get(base, "")
    symbol = raw
    ens = symbol_to_ens.get(symbol.upper(), "")
    if ens:
        return ens, ens, symbol
    return symbol.upper(), "", symbol


def aggregate_coloc_gene_evidence(coloc: pd.DataFrame, variants: pd.DataFrame,
                                  strong_pp4: float,
                                  suggestive_pp4: float) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Return (gene-level formal evidence, locus-level QTL evidence)."""
    if coloc.empty:
        return pd.DataFrame(), pd.DataFrame()

    ens_to_symbol, symbol_to_ens = build_ensembl_symbol_maps(variants)
    x = coloc.copy()
    x["COLOC_TESTED_BOOL"] = x.get(
        "COLOC_TESTED", pd.Series("NO", index=x.index)
    ).astype(str).str.upper().eq("YES")
    x["STATUS_COMPLETE_BOOL"] = x.get(
        "STATUS", pd.Series("", index=x.index)
    ).astype(str).str.upper().eq("COMPLETE")
    x["FORMAL_VALID"] = x["COLOC_TESTED_BOOL"] & x["STATUS_COMPLETE_BOOL"]
    x["MAX_PP_H4"] = pd.to_numeric(x.get("MAX_PP_H4"), errors="coerce")
    x["MAX_PP_H3"] = pd.to_numeric(x.get("MAX_PP_H3"), errors="coerce")
    x["PRIOR_ROBUST_BOOL"] = x.get(
        "PRIOR_ROBUST_STRONG", pd.Series("NO", index=x.index)
    ).astype(str).str.upper().eq("YES")
    x["COLOC_STRONG_BOOL"] = x.get(
        "COLOCALIZED_STRONG", pd.Series("NO", index=x.index)
    ).astype(str).str.upper().eq("YES") | (
        x["FORMAL_VALID"] & (x["MAX_PP_H4"] >= strong_pp4)
    )
    x["COLOC_SUGGESTIVE_BOOL"] = (
        x["FORMAL_VALID"]
        & (x["MAX_PP_H4"] >= suggestive_pp4)
        & ~x["COLOC_STRONG_BOOL"]
    )

    mapped = x.apply(
        lambda row: map_coloc_gene(row, ens_to_symbol, symbol_to_ens),
        axis=1,
        result_type="expand",
    )
    mapped.columns = ["GENE_KEY", "GENE_ID_CANONICAL", "GENE_SYMBOL_CANONICAL"]
    x = pd.concat([x, mapped], axis=1)

    # Locus-level QTL evidence includes caQTL even when no target gene is known.
    locus_rows = []
    for (study, locus, qtl), g in x.groupby(
        ["STUDY_ACCESSION", "LOCUS_ID", "QTL_TYPE"], dropna=False, sort=False
    ):
        valid = g[g["FORMAL_VALID"]].copy()
        if not valid.empty and valid["MAX_PP_H4"].notna().any():
            idx = valid["MAX_PP_H4"].idxmax()
            best = valid.loc[idx]
            max_h4 = float(best["MAX_PP_H4"])
            max_h3 = float(best["MAX_PP_H3"]) if pd.notna(best["MAX_PP_H3"]) else np.nan
            best_gene = str(best.get("GENE_SYMBOL_CANONICAL", "")) or str(best.get("GENE_ID_CANONICAL", ""))
            best_gene_id = str(best.get("GENE_ID_CANONICAL", ""))
            best_tissue = str(best.get("TISSUE", ""))
            best_trait = str(best.get("MOLECULAR_TRAIT_ID", ""))
            best_dataset = str(best.get("DATASET", ""))
        else:
            max_h4 = np.nan
            max_h3 = np.nan
            best_gene = best_gene_id = best_tissue = best_trait = best_dataset = ""
        locus_rows.append({
            "STUDY_ACCESSION": study,
            "LOCUS_ID": locus,
            "QTL_TYPE": str(qtl),
            "N_CANDIDATE_ROWS": len(g),
            "N_FORMALLY_TESTED": int(g["FORMAL_VALID"].sum()),
            "N_STRONG": int((g["FORMAL_VALID"] & g["COLOC_STRONG_BOOL"]).sum()),
            "N_SUGGESTIVE": int((g["FORMAL_VALID"] & g["COLOC_SUGGESTIVE_BOOL"]).sum()),
            "N_PRIOR_ROBUST_STRONG": int((g["FORMAL_VALID"] & g["PRIOR_ROBUST_BOOL"]).sum()),
            "MAX_PP_H4": max_h4,
            "MAX_PP_H3": max_h3,
            "BEST_GENE": best_gene,
            "BEST_GENE_ID": best_gene_id,
            "BEST_TISSUE": best_tissue,
            "BEST_TRAIT": best_trait,
            "BEST_DATASET": best_dataset,
        })
    locus_qtl = pd.DataFrame(locus_rows)

    gene_x = x[x["GENE_KEY"].astype(str).str.strip() != ""].copy()
    if gene_x.empty:
        return pd.DataFrame(), locus_qtl

    gene_rows = []
    for (study, locus, gene_key), g in gene_x.groupby(
        ["STUDY_ACCESSION", "LOCUS_ID", "GENE_KEY"], dropna=False, sort=False
    ):
        row = {
            "STUDY_ACCESSION": study,
            "LOCUS_ID": locus,
            "GENE_KEY": gene_key,
            "GENE_ID_COLOC": str(first_nonempty(g["GENE_ID_CANONICAL"].tolist())),
            "GENE_SYMBOL_COLOC": str(first_nonempty(g["GENE_SYMBOL_CANONICAL"].tolist())),
            "N_COLOC_CANDIDATES": len(g),
            "N_FORMALLY_TESTED": int(g["FORMAL_VALID"].sum()),
            "N_STRONG_COLOC_ROWS": int((g["FORMAL_VALID"] & g["COLOC_STRONG_BOOL"]).sum()),
            "N_SUGGESTIVE_COLOC_ROWS": int((g["FORMAL_VALID"] & g["COLOC_SUGGESTIVE_BOOL"]).sum()),
            "ANY_PRIOR_ROBUST_STRONG": bool((g["FORMAL_VALID"] & g["PRIOR_ROBUST_BOOL"]).any()),
        }

        strong_types = []
        suggestive_types = []
        tested_types = []
        max_pp4_all = []

        for qtl_type in sorted(g["QTL_TYPE"].fillna("").astype(str).unique()):
            if not qtl_type:
                continue
            q = g[g["QTL_TYPE"].astype(str) == qtl_type].copy()
            valid = q[q["FORMAL_VALID"]].copy()
            qkey = re.sub(r"[^A-Za-z0-9]+", "_", qtl_type).upper().strip("_")
            if valid.empty or not valid["MAX_PP_H4"].notna().any():
                row[f"{qkey}_PP4"] = np.nan
                row[f"{qkey}_PP3"] = np.nan
                row[f"{qkey}_TISSUE"] = ""
                row[f"{qkey}_TRAIT"] = ""
                row[f"{qkey}_STRONG"] = False
                row[f"{qkey}_SUGGESTIVE"] = False
                row[f"{qkey}_PRIOR_ROBUST"] = False
                continue
            idx = valid["MAX_PP_H4"].idxmax()
            best = valid.loc[idx]
            pp4 = float(best["MAX_PP_H4"])
            pp3 = float(best["MAX_PP_H3"]) if pd.notna(best["MAX_PP_H3"]) else np.nan
            is_strong = bool(valid["COLOC_STRONG_BOOL"].any())
            is_suggestive = bool(valid["COLOC_SUGGESTIVE_BOOL"].any())
            is_robust = bool(valid["PRIOR_ROBUST_BOOL"].any())
            row[f"{qkey}_PP4"] = pp4
            row[f"{qkey}_PP3"] = pp3
            row[f"{qkey}_TISSUE"] = str(best.get("TISSUE", ""))
            row[f"{qkey}_TRAIT"] = str(best.get("MOLECULAR_TRAIT_ID", ""))
            row[f"{qkey}_DATASET"] = str(best.get("DATASET", ""))
            row[f"{qkey}_STRONG"] = is_strong
            row[f"{qkey}_SUGGESTIVE"] = is_suggestive
            row[f"{qkey}_PRIOR_ROBUST"] = is_robust
            tested_types.append(qtl_type)
            if is_strong:
                strong_types.append(qtl_type)
            elif is_suggestive:
                suggestive_types.append(qtl_type)
            max_pp4_all.append(pp4)

        row["FORMALLY_TESTED_QTL_TYPES"] = ";".join(tested_types)
        row["STRONG_QTL_TYPES"] = ";".join(strong_types)
        row["SUGGESTIVE_QTL_TYPES"] = ";".join(suggestive_types)
        row["N_STRONG_QTL_TYPES"] = len(set(strong_types))
        row["N_SUGGESTIVE_QTL_TYPES"] = len(set(suggestive_types))
        row["MAX_PP4"] = max(max_pp4_all) if max_pp4_all else np.nan
        gene_rows.append(row)

    return pd.DataFrame(gene_rows), locus_qtl


