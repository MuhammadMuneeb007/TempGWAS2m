def outer_merge_gene_evidence(variant_gene: pd.DataFrame,
                              coloc_gene: pd.DataFrame) -> pd.DataFrame:
    keys = ["STUDY_ACCESSION", "LOCUS_ID", "GENE_KEY"]
    if variant_gene.empty and coloc_gene.empty:
        return pd.DataFrame()
    if variant_gene.empty:
        x = coloc_gene.copy()
    elif coloc_gene.empty:
        x = variant_gene.copy()
    else:
        x = variant_gene.merge(coloc_gene, on=keys, how="outer", validate="one_to_one")

    x["GENE_ID"] = [
        str(first_nonempty([row.get("GENE_ID", ""), row.get("GENE_ID_COLOC", "")]))
        for _, row in x.iterrows()
    ]
    x["GENE_SYMBOL"] = [
        str(first_nonempty([row.get("GENE_SYMBOL", ""), row.get("GENE_SYMBOL_COLOC", "")]))
        for _, row in x.iterrows()
    ]
    x["GENE_DISPLAY"] = [
        str(first_nonempty([row.get("GENE_SYMBOL", ""), row.get("GENE_ID", ""), row.get("GENE_KEY", "")]))
        for _, row in x.iterrows()
    ]

    numeric_defaults = {
        "MAX_PIP": np.nan,
        "N_95CS_GENE_VARIANTS": 0,
        "N_GENE_LINKED_VARIANTS": 0,
        "MAX_SPLICEAI_DS": np.nan,
        "MAX_PANGOLIN_ABS": np.nan,
        "MAX_SPLICE_EVIDENCE_SOURCES": 0,
        "N_STRONG_QTL_TYPES": 0,
        "N_SUGGESTIVE_QTL_TYPES": 0,
        "N_FORMALLY_TESTED": 0,
        "MAX_PP4": np.nan,
    }
    for col, default in numeric_defaults.items():
        if col not in x.columns:
            x[col] = default
        x[col] = pd.to_numeric(x[col], errors="coerce")

    bool_defaults = {
        "ANY_PANGOLIN_TOP5": False,
        "ANY_PRIOR_ROBUST_STRONG": False,
    }
    for col, default in bool_defaults.items():
        if col not in x.columns:
            x[col] = default
        x[col] = bool_series(x[col])

    for col in ["BEST_FUNCTIONAL_CATEGORY", "BEST_IMPACT", "STRONG_QTL_TYPES", "SUGGESTIVE_QTL_TYPES"]:
        if col not in x.columns:
            x[col] = ""
        x[col] = x[col].fillna("").astype(str)

    return x


def assign_evidence_tier(row: pd.Series) -> str:
    strong_types = safe_int0(row.get("N_STRONG_QTL_TYPES", 0))
    sugg_types = safe_int0(row.get("N_SUGGESTIVE_QTL_TYPES", 0))
    robust = boolish(row.get("ANY_PRIOR_ROBUST_STRONG", False))
    pip = row.get("MAX_PIP", np.nan)
    pip = float(pip) if pd.notna(pip) else np.nan
    category = str(row.get("BEST_FUNCTIONAL_CATEGORY", "")).upper()
    impact = str(row.get("BEST_IMPACT", "")).upper()
    spliceai = row.get("MAX_SPLICEAI_DS", np.nan)
    spliceai = float(spliceai) if pd.notna(spliceai) else np.nan
    pang_top5 = boolish(row.get("ANY_PANGOLIN_TOP5", False))
    nsplice = safe_int0(row.get("MAX_SPLICE_EVIDENCE_SOURCES", 0))

    damaging_coding = (
        category in {"CODING", "SPLICING"}
        and impact in {"HIGH", "MODERATE"}
        and pd.notna(pip) and pip >= 0.10
    )

    if robust or strong_types >= 2 or (strong_types >= 1 and pd.notna(pip) and pip >= 0.10) or damaging_coding:
        return "TIER1_HIGH"

    if (
        strong_types >= 1
        or (sugg_types >= 1 and pd.notna(pip) and pip >= 0.01)
        or (pd.notna(spliceai) and spliceai >= 0.50 and pd.notna(pip) and pip >= 0.01)
        or (pang_top5 and pd.notna(pip) and pip >= 0.01)
        or (nsplice >= 2 and pd.notna(pip) and pip >= 0.01)
    ):
        return "TIER2_MODERATE"

    if sugg_types >= 1 or (pd.notna(pip) and pip >= 0.01) or category in {"CODING", "SPLICING", "REGULATORY"}:
        return "TIER3_SUPPORTING"

    return "TIER4_WEAK"


def mechanism_from_row(row: pd.Series) -> str:
    strong = {x.lower() for x in split_tokens(row.get("STRONG_QTL_TYPES", ""))}
    suggestive = {x.lower() for x in split_tokens(row.get("SUGGESTIVE_QTL_TYPES", ""))}
    category = str(row.get("BEST_FUNCTIONAL_CATEGORY", "")).upper()
    spliceai = row.get("MAX_SPLICEAI_DS", np.nan)
    spliceai = float(spliceai) if pd.notna(spliceai) else np.nan
    nsplice = safe_int0(row.get("MAX_SPLICE_EVIDENCE_SOURCES", 0))

    mechanisms = []
    if "eqtl" in strong:
        mechanisms.append("EXPRESSION_REGULATION")
    if "sqtl" in strong:
        mechanisms.append("SPLICING_REGULATION")
    if "pqtl" in strong:
        mechanisms.append("PROTEIN_ABUNDANCE")
    if "caqtl" in strong:
        mechanisms.append("CHROMATIN_REGULATION")
    if "meqtl" in strong or "mqtl" in strong:
        mechanisms.append("DNA_METHYLATION_REGULATION")
    if "hqtl" in strong:
        mechanisms.append("HISTONE_REGULATION")

    if category == "CODING":
        mechanisms.append("CODING_VARIANT")
    if category == "SPLICING" or (pd.notna(spliceai) and spliceai >= 0.50) or nsplice >= 2:
        mechanisms.append("PREDICTED_SPLICING")
    if category == "REGULATORY" and "CHROMATIN_REGULATION" not in mechanisms:
        mechanisms.append("REGULATORY_VARIANT")

    if not mechanisms and suggestive:
        for qtl in sorted(suggestive):
            label = {
                "eqtl": "SUGGESTIVE_EXPRESSION_REGULATION",
                "sqtl": "SUGGESTIVE_SPLICING_REGULATION",
                "pqtl": "SUGGESTIVE_PROTEIN_ABUNDANCE",
                "caqtl": "SUGGESTIVE_CHROMATIN_REGULATION",
            }.get(qtl, f"SUGGESTIVE_{qtl.upper()}")
            mechanisms.append(label)

    if not mechanisms:
        if category:
            mechanisms.append(f"ANNOTATION_{category}")
        else:
            mechanisms.append("GENE_LINK_WITHOUT_RESOLVED_MECHANISM")

    # Preserve order, remove duplicates.
    unique = []
    for m in mechanisms:
        if m not in unique:
            unique.append(m)
    return ";".join(unique)


def ranking_reason(row: pd.Series) -> str:
    parts = []
    if boolish(row.get("ANY_PRIOR_ROBUST_STRONG", False)):
        parts.append("prior-robust formal coloc")
    strong = split_tokens(row.get("STRONG_QTL_TYPES", ""))
    suggestive = split_tokens(row.get("SUGGESTIVE_QTL_TYPES", ""))
    if strong:
        parts.append("strong coloc: " + ",".join(strong))
    elif suggestive:
        parts.append("suggestive coloc: " + ",".join(suggestive))
    pip = row.get("MAX_PIP", np.nan)
    if pd.notna(pip):
        parts.append(f"max PIP={float(pip):.3g}")
    cat = str(row.get("BEST_FUNCTIONAL_CATEGORY", "")).strip()
    impact = str(row.get("BEST_IMPACT", "")).strip()
    if cat:
        parts.append(f"VEP={cat}" + (f"/{impact}" if impact else ""))
    sai = row.get("MAX_SPLICEAI_DS", np.nan)
    if pd.notna(sai) and float(sai) >= 0.20:
        parts.append(f"SpliceAI={float(sai):.3g}")
    if boolish(row.get("ANY_PANGOLIN_TOP5", False)):
        parts.append("Pangolin top-5%")
    nsp = safe_int0(row.get("MAX_SPLICE_EVIDENCE_SOURCES", 0))
    if nsp >= 2:
        parts.append(f"splice sources={nsp}")
    return "; ".join(parts) if parts else "weak/limited internal evidence"


def rank_genes(gene_evidence: pd.DataFrame) -> pd.DataFrame:
    if gene_evidence.empty:
        return gene_evidence
    x = gene_evidence.copy()
    x["EVIDENCE_TIER"] = x.apply(assign_evidence_tier, axis=1)
    x["TIER_RANK"] = x["EVIDENCE_TIER"].map(TIER_RANK).fillna(99).astype(int)
    x["DOMINANT_MECHANISM"] = x.apply(mechanism_from_row, axis=1)
    x["RANKING_REASON"] = x.apply(ranking_reason, axis=1)

    # Sorting metrics; no opaque weighted score.
    x["_ROBUST"] = bool_series(x["ANY_PRIOR_ROBUST_STRONG"]).astype(int)
    x["_MAX_PP4"] = pd.to_numeric(x["MAX_PP4"], errors="coerce").fillna(-1.0)
    x["_MAX_PIP"] = pd.to_numeric(x["MAX_PIP"], errors="coerce").fillna(-1.0)
    x["_FUNC_RANK"] = x["BEST_FUNCTIONAL_CATEGORY"].str.upper().map(FUNCTIONAL_CATEGORY_RANK).fillna(99)
    x["_IMPACT_RANK"] = x["BEST_IMPACT"].str.upper().map(IMPACT_RANK).fillna(99)
    x["_SPLICE"] = pd.to_numeric(x["MAX_SPLICE_EVIDENCE_SOURCES"], errors="coerce").fillna(0)

    x = x.sort_values(
        [
            "STUDY_ACCESSION", "LOCUS_ID", "TIER_RANK",
            "N_STRONG_QTL_TYPES", "_ROBUST", "_MAX_PP4", "_MAX_PIP",
            "_FUNC_RANK", "_IMPACT_RANK", "_SPLICE", "GENE_DISPLAY",
        ],
        ascending=[True, True, True, False, False, False, False, True, True, False, True],
        kind="stable",
    ).reset_index(drop=True)
    x["GENE_RANK"] = x.groupby(["STUDY_ACCESSION", "LOCUS_ID"], sort=False).cumcount() + 1
    return x.drop(columns=["_ROBUST", "_MAX_PP4", "_MAX_PIP", "_FUNC_RANK", "_IMPACT_RANK", "_SPLICE"])


