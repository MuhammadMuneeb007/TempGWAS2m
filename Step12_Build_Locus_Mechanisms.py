"""
================================================================================
GWAS2m STEP 12
INTEGRATED LOCUS -> GENE -> MECHANISM MASTER TABLE
================================================================================

PURPOSE
-------
Step12 integrates GWAS2m's own evidence AFTER strict Step11 molecular-QTL
colocalisation. It does NOT use Open Targets. Open Targets must remain an
independent downstream benchmark.

Evidence integrated per phenotype / ancestry:
    Step06  fine-mapping: loci, variants, PIP, 95% credible-set membership
    Step07  VEP annotation: genes, consequences, impact, functional category
    Step08  descriptive GTEx v11 eQTL/sQTL overlaps (carried downstream)
    Step09  SpliceAI predictions
    Step10  Pangolin + integrated splice evidence
    Step11  strict formal coloc.susie results:
            eQTL / sQTL / pQTL / caQTL / other configured molecular-QTLs

MAIN SCIENTIFIC OUTPUTS
-----------------------
1. Variant evidence table
2. Formal molecular-QTL colocalisation table
3. Locus x gene evidence table
4. Ranked/prioritised genes per locus
5. Final locus -> mechanism summary (printed to screen AND saved)
6. Unresolved loci (do not force a gene)
7. Phenotype-level consensus loci across studies
8. Unique prioritised-gene list for Step13 pathway/network analysis

IMPORTANT RULES
---------------
* Missing data/resource errors are never converted into biological negatives.
* Step11 formal evidence counts only rows with COLOC_TESTED=YES and STATUS=COMPLETE.
* eQTL, sQTL, pQTL and caQTL remain separate evidence modalities.
* Gene ranking is internal to GWAS2m; Open Targets is NOT used here.
* Rankings are transparent/lexicographic, not a black-box ML score.
* Non-coding loci without a defensible gene link remain UNRESOLVED.
* A caQTL peak with no target gene is retained as a regulatory mechanism, not
  forcibly assigned to the nearest gene.

RUN
---
    python Step12_Build_Locus_Mechanisms.py \
        --phenotype "parkinson's disease" \
        --ancestry EUR

Single study:
    python Step12_Build_Locus_Mechanisms.py \
        --phenotype "parkinson's disease" \
        --ancestry EUR \
        --study GCST90473307

Allow incomplete/failed Step11 loci for exploratory inspection only:
    python Step12_Build_Locus_Mechanisms.py \
        --phenotype "parkinson's disease" \
        --ancestry EUR \
        --allow-incomplete-step11

OUTPUT
------
12_locus_mechanisms/<phenotype>/<ancestry>/
    all_variant_evidence.tsv.gz
    formal_coloc_all.tsv
    all_gene_evidence.tsv
    prioritized_genes.tsv
    locus_mechanism_summary.tsv
    unresolved_loci.tsv
    phenotype_consensus_loci.tsv
    pathway_input_genes.tsv
    step12_input_audit.tsv
    step12_summary.json

================================================================================
"""

