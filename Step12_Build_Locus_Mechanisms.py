def normalize_text(value) -> str:
    x = str(value).strip().lower()
    x = re.sub(r"[^a-z0-9]+", " ", x)
    x = re.sub(r"\s+", " ", x)
    return x.strip()


def slugify(value) -> str:
    return normalize_text(value).replace(" ", "_")


def canonical_ancestry(value: str) -> tuple[str, str]:
    key = normalize_text(value)
    if key not in ANCESTRY:
        raise SystemExit(
            f"Unsupported ancestry: {value!r}. Use EUR/AFR/EAS/SAS/AMR "
            "or the corresponding full label."
        )
    return ANCESTRY[key]


def canonical_chr(value) -> str:
    if value is None or pd.isna(value):
        return ""
    x = str(value).strip()
    x = re.sub(r"^chr", "", x, flags=re.I)
    if x.endswith(".0"):
        x = x[:-2]
    return x.upper()


def safe_numeric(value):
    return pd.to_numeric(value, errors="coerce")


def safe_int0(value) -> int:
    if value is None:
        return 0
    try:
        if pd.isna(value):
            return 0
    except Exception:
        pass
    try:
        number = float(value)
    except (TypeError, ValueError):
        return 0
    if not np.isfinite(number):
        return 0
    return int(number)


def boolish(value) -> bool:
    if isinstance(value, (bool, np.bool_)):
        return bool(value)
    if value is None:
        return False
    return str(value).strip().lower() in {
        "1", "true", "t", "yes", "y", "on",
    }


def bool_series(series: pd.Series) -> pd.Series:
    return series.map(boolish).fillna(False).astype(bool)


def split_tokens(value) -> list[str]:
    if value is None:
        return []
    try:
        if pd.isna(value):
            return []
    except Exception:
        pass
    x = str(value).strip()
    if not x or x.lower() in {"nan", "none", "na", "null", "."}:
        return []
    parts = re.split(r"[;,|]", x)
    out = []
    for token in parts:
        token = token.strip()
        if token and token not in out:
            out.append(token)
    return out


def join_unique(values: Iterable) -> str:
    out: list[str] = []
    for value in values:
        for token in split_tokens(value):
            if token not in out:
                out.append(token)
    return ";".join(out)


def first_nonempty(values: Iterable, default=""):
    for value in values:
        if value is None:
            continue
        try:
            if pd.isna(value):
                continue
        except Exception:
            pass
        x = str(value).strip()
        if x and x.lower() not in {"nan", "none", "na", "null", "."}:
            return value
    return default


def read_table(path: Path | None, required: bool = False) -> pd.DataFrame:
    if path is None or not path.exists() or path.stat().st_size == 0:
        if required:
            raise FileNotFoundError(f"Missing/empty required table: {path}")
        return pd.DataFrame()
    try:
        return pd.read_csv(path, sep="\t", compression="infer", low_memory=False)
    except pd.errors.EmptyDataError:
        if required:
            raise RuntimeError(f"Required table has no columns: {path}")
        return pd.DataFrame()


def safe_json(path: Path | None) -> dict:
    if path is None or not path.exists() or path.stat().st_size == 0:
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return {}


def write_json(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(payload, indent=2, sort_keys=True, default=json_safe),
        encoding="utf-8",
    )


def json_safe(obj):
    if isinstance(obj, (np.integer,)):
        return int(obj)
    if isinstance(obj, (np.floating,)):
        return None if np.isnan(obj) else float(obj)
    if isinstance(obj, (np.bool_,)):
        return bool(obj)
    if isinstance(obj, Path):
        return str(obj)
    if isinstance(obj, np.ndarray):
        return obj.tolist()
    try:
        if pd.isna(obj):
            return None
    except Exception:
        pass
    raise TypeError(f"Not JSON serialisable: {type(obj).__name__}")


def first_existing(base: Path, patterns: list[str]) -> Path | None:
    for pattern in patterns:
        if any(ch in pattern for ch in "*?[]"):
            hits = sorted(base.glob(pattern)) if base.exists() else []
            for hit in hits:
                if hit.exists() and hit.stat().st_size > 0:
                    return hit
        else:
            hit = base / pattern
            if hit.exists() and hit.stat().st_size > 0:
                return hit
    return None


def gene_base(value) -> str:
    if value is None:
        return ""
    try:
        if pd.isna(value):
            return ""
    except Exception:
        pass
    x = str(value).strip()
    if not x or x.lower() in {"nan", "none", "na", "null", "."}:
        return ""
    match = re.search(r"(ENSG\d+)", x, re.I)
    if match:
        return match.group(1).upper()
    return x


def canonical_variant_from_row(row: pd.Series) -> str:
    chrom = canonical_chr(
        first_nonempty([
            row.get("CHR"), row.get("CHROM"), row.get("chromosome"),
            row.get("PANGOLIN_CHROM"),
        ])
    )
    pos = first_nonempty([
        row.get("REFERENCE_POS"), row.get("POS"), row.get("position"),
        row.get("PANGOLIN_POS"),
    ], default=np.nan)
    ref = str(first_nonempty([
        row.get("REFERENCE_REF"), row.get("REF"), row.get("ref"),
        row.get("PANGOLIN_REF"),
    ])).upper().strip()
    alt = str(first_nonempty([
        row.get("REFERENCE_ALT"), row.get("ALT"), row.get("alt"),
        row.get("PANGOLIN_ALT"),
    ])).upper().strip()
    try:
        pos = int(float(pos))
    except Exception:
        return str(first_nonempty([row.get("REFERENCE_ID"), row.get("SNPID"), row.get("rsID")]))
    if not chrom or not ref or not alt:
        return str(first_nonempty([row.get("REFERENCE_ID"), row.get("SNPID"), row.get("rsID")]))
    return f"{chrom}:{pos}:{ref}:{alt}"


