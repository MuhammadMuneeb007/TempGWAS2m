def load_step07_variants(path: Path) -> pd.DataFrame:
    df = pd.read_csv(path, sep="\t", low_memory=False)

    required = [
        "VEP_ID",
        "LOCUS_ID",
        "CHR",
        "REFERENCE_POS",
        "REFERENCE_REF",
        "REFERENCE_ALT",
        "PIP",
    ]
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise RuntimeError(
            f"Step07 variant summary is missing required columns {missing}:\n{path}"
        )

    df["CHR"] = (
        df["CHR"].astype(str).str.replace(r"^chr", "", regex=True, case=False)
    )
    df["CHR"] = pd.to_numeric(df["CHR"], errors="coerce")
    df["REFERENCE_POS"] = pd.to_numeric(df["REFERENCE_POS"], errors="coerce")
    df["PIP"] = pd.to_numeric(df["PIP"], errors="coerce")

    df = df.dropna(
        subset=[
            "VEP_ID",
            "LOCUS_ID",
            "CHR",
            "REFERENCE_POS",
            "REFERENCE_REF",
            "REFERENCE_ALT",
        ]
    ).copy()

    df = df[df["CHR"].between(1, 22, inclusive="both")].copy()
    df["CHR"] = df["CHR"].astype(int)
    df["REFERENCE_POS"] = df["REFERENCE_POS"].astype(int)
    df["REFERENCE_REF"] = df["REFERENCE_REF"].astype(str).str.upper().str.strip()
    df["REFERENCE_ALT"] = df["REFERENCE_ALT"].astype(str).str.upper().str.strip()

    # One Step07 row per VEP_ID is expected. Keep highest PIP if duplicates exist.
    df = (
        df.sort_values(["LOCUS_ID", "PIP"], ascending=[True, False], kind="stable")
        .drop_duplicates(subset=["VEP_ID"], keep="first")
        .reset_index(drop=True)
    )

    df["GTEX_CONSTRUCTED_VARIANT_ID"] = (
        "chr"
        + df["CHR"].astype(str)
        + "_"
        + df["REFERENCE_POS"].astype(str)
        + "_"
        + df["REFERENCE_REF"]
        + "_"
        + df["REFERENCE_ALT"]
        + "_b38"
    )

    df["GTEX_MATCH_KEY"] = (
        df["CHR"].astype(str)
        + ":"
        + df["REFERENCE_POS"].astype(str)
        + ":"
        + df["REFERENCE_REF"]
        + ":"
        + df["REFERENCE_ALT"]
    )

    return df


