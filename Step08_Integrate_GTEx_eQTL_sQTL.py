def resolve_gtex_root(root: Path, explicit: str | None) -> Path:
    candidates = []
    if explicit:
        candidates.append(Path(explicit).expanduser())

    env_value = os.environ.get("GTEX_V11")
    if env_value:
        candidates.append(Path(env_value).expanduser())

    resource_env = read_resource_env(root)
    if resource_env.get("GTEX_V11"):
        candidates.append(Path(resource_env["GTEX_V11"]).expanduser())

    candidates.append(root / "resources" / "gtex" / "v11")

    for candidate in candidates:
        candidate = candidate.resolve()
        if candidate.exists() and candidate.is_dir():
            return candidate

    raise FileNotFoundError(
        "Could not find GTEx v11 resources. Pass --gtex-root or ensure "
        "resource_paths.env exports GTEX_V11."
    )


def discover_significant_pair_files(directory: Path, qtl_type: str) -> list[Path]:
    if not directory.exists():
        return []

    candidates = []
    for path in directory.rglob("*"):
        if not path.is_file():
            continue
        name = path.name.lower()
        if name.startswith("."):
            continue
        if not (
            name.endswith(".txt.gz")
            or name.endswith(".tsv.gz")
            or name.endswith(".txt")
            or name.endswith(".tsv")
        ):
            continue
        # We want significant pair-level outputs, not eGenes/sGenes summary tables.
        if "signif" not in name and "pair" not in name:
            continue
        if "egenes" in name or "sgenes" in name:
            continue
        candidates.append(path.resolve())

    # If naming differs in a future extraction, inspect headers as a fallback.
    if not candidates:
        for path in directory.rglob("*"):
            if not path.is_file():
                continue
            name = path.name.lower()
            if not (
                name.endswith(".txt.gz")
                or name.endswith(".tsv.gz")
                or name.endswith(".txt")
                or name.endswith(".tsv")
            ):
                continue
            try:
                header = pd.read_csv(path, sep="\t", nrows=0, compression="infer")
            except Exception:
                continue
            if first_existing(header.columns, ["variant_id", "variantId", "variant"]):
                if qtl_type == "EQTL" and first_existing(header.columns, ["gene_id", "geneId", "gencodeId"]):
                    candidates.append(path.resolve())
                elif qtl_type == "SQTL" and first_existing(
                    header.columns,
                    ["phenotype_id", "phenotypeId", "gene_id", "geneId", "gencodeId"],
                ):
                    candidates.append(path.resolve())

    return sorted(set(candidates))


def tissue_from_filename(path: Path) -> str:
    name = path.name
    suffix_patterns = [
        r"\.v11\.signif_variant_gene_pairs\.txt\.gz$",
        r"\.v11\.signif_variant_gene_pairs\.txt$",
        r"\.signif_variant_gene_pairs\.txt\.gz$",
        r"\.signif_variant_gene_pairs\.txt$",
        r"\.signif_pairs\.txt\.gz$",
        r"\.signif_pairs\.txt$",
        r"\.txt\.gz$",
        r"\.tsv\.gz$",
        r"\.txt$",
        r"\.tsv$",
    ]
    tissue = name
    for pattern in suffix_patterns:
        new = re.sub(pattern, "", tissue, flags=re.IGNORECASE)
        if new != tissue:
            tissue = new
            break
    # Remove common release/type prefixes/suffixes while preserving GTEx tissue IDs.
    tissue = re.sub(r"^GTEx_Analysis_v11_", "", tissue, flags=re.IGNORECASE)
    tissue = re.sub(r"_(eQTL|sQTL)$", "", tissue, flags=re.IGNORECASE)
    return tissue


def resource_signature(paths: list[Path]) -> str:
    records = []
    for path in sorted(paths):
        st = path.stat()
        records.append(f"{path}|{st.st_size}|{st.st_mtime_ns}")
    return sha256_strings(records)


