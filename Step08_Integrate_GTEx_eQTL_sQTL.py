def worker_mode() -> None:
    task_value = os.environ.get("SLURM_ARRAY_TASK_ID")
    manifest_value = os.environ.get("GWAS_QTL_MANIFEST")
    if not task_value:
        raise RuntimeError("SLURM_ARRAY_TASK_ID is not defined")
    if not manifest_value:
        raise RuntimeError("GWAS_QTL_MANIFEST is not defined")

    task_id = int(task_value)
    manifest_file = Path(manifest_value).resolve()
    if not manifest_file.exists():
        raise FileNotFoundError(f"QTL manifest not found: {manifest_file}")

    manifest = pd.read_csv(manifest_file, sep="\t", dtype=str, low_memory=False)
    required = [
        "QTL_TASK_ID",
        "STUDY_ACCESSION",
        "PHENOTYPE",
        "ANCESTRY_CODE",
        "ANCESTRY_LABEL",
        "STEP07_VARIANT_FILE",
        "OUTPUT_DIR",
        "GTEX_ROOT",
        "GTEX_EQTL_ROOT",
        "GTEX_SQTL_ROOT",
        "GTEX_LOOKUP_FILE",
        "CHUNK_SIZE",
    ]
    missing = [c for c in required if c not in manifest.columns]
    if missing:
        raise RuntimeError(f"QTL manifest is missing required columns: {missing}")

    task_numbers = pd.to_numeric(manifest["QTL_TASK_ID"], errors="coerce")
    selected = manifest.loc[task_numbers == task_id]
    if len(selected) != 1:
        raise RuntimeError(
            f"Expected exactly one QTL manifest row for task {task_id}; found {len(selected)}"
        )

    row = selected.iloc[0]
    accession = str(row["STUDY_ACCESSION"]).strip()
    phenotype = str(row["PHENOTYPE"]).strip()
    ancestry_code = str(row["ANCESTRY_CODE"]).strip().upper()
    ancestry_label = str(row["ANCESTRY_LABEL"]).strip()
    input_file = Path(row["STEP07_VARIANT_FILE"]).resolve()
    output_dir = Path(row["OUTPUT_DIR"]).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    force = str(row.get("FORCE", "False")).lower() in {"true", "1", "yes", "y"}
    force = force or os.environ.get("STEP08_FORCE", "0") == "1"
    rebuild_cache = str(row.get("REBUILD_CACHE", "False")).lower() in {"true", "1", "yes", "y"}
    rebuild_cache = rebuild_cache or os.environ.get("STEP08_REBUILD_CACHE", "0") == "1"

    mapping_output = output_dir / f"{accession}_GTEx_variant_mapping.tsv"
    eqtl_output = output_dir / f"{accession}_GTEx_eQTL.tsv.gz"
    sqtl_output = output_dir / f"{accession}_GTEx_sQTL.tsv.gz"
    gene_output = output_dir / f"{accession}_GTEx_variant_gene_evidence.tsv.gz"
    variant_output = output_dir / f"{accession}_GTEx_QTL_variant_summary.tsv"
    locus_output = output_dir / f"{accession}_GTEx_QTL_locus_summary.tsv"
    summary_output = output_dir / "qtl_summary.json"
    failed_output = output_dir / "QTL_FAILED.txt"

    if (
        not force
        and variant_output.exists()
        and variant_output.stat().st_size > 0
        and summary_output.exists()
        and summary_output.stat().st_size > 0
        and not failed_output.exists()
    ):
        banner("STEP 08 ALREADY COMPLETE")
        print(f"Study: {accession}")
        print(f"Output: {output_dir}")
        return

    banner("STEP 08 - GTEx v11 ALL-TISSUE QTL WORKER")
    print(f"Task       : {task_id}")
    print(f"Study      : {accession}")
    print(f"Phenotype  : {phenotype}")
    print(f"Ancestry   : {ancestry_label} ({ancestry_code})")
    print(f"Input      : {input_file}")
    print(f"GTEx       : {row['GTEX_ROOT']}")
    print("Tissues    : ALL GTEx v11 tissues")
    print(f"Output     : {output_dir}")

    try:
        if not input_file.exists() or input_file.stat().st_size == 0:
            raise FileNotFoundError(f"Step07 variant file missing/empty: {input_file}")

        # qtl_root is the parent containing all study dirs + shared cache.
        qtl_root = output_dir.parent
        cache = ensure_shared_cache(
            manifest=manifest,
            qtl_root=qtl_root,
            force_rebuild=rebuild_cache,
        )

        variants = load_step07_variants(input_file)
        variants["STUDY_ACCESSION"] = accession
        variants["PHENOTYPE"] = phenotype
        variants["ANCESTRY_CODE"] = ancestry_code
        variants["ANCESTRY_LABEL"] = ancestry_label

        shared_mapping = pd.read_csv(cache["mapping"], sep="\t", compression="gzip", low_memory=False)
        variants = variants.merge(
            shared_mapping[
                [
                    "GTEX_MATCH_KEY",
                    "GTEX_VARIANT_ID",
                    "GTEX_SNP_ID",
                    "GTEX_MAPPING_METHOD",
                ]
            ],
            on="GTEX_MATCH_KEY",
            how="left",
            validate="many_to_one",
        )
        variants["GTEX_VARIANT_ID"] = variants["GTEX_VARIANT_ID"].fillna(
            variants["GTEX_CONSTRUCTED_VARIANT_ID"]
        )
        variants.to_csv(mapping_output, sep="\t", index=False)

        study_ids = set(variants["GTEX_VARIANT_ID"].dropna().astype(str))
        study_ids.update(variants["GTEX_CONSTRUCTED_VARIANT_ID"].dropna().astype(str))

        shared_eqtl = pd.read_csv(cache["eqtl"], sep="\t", compression="gzip", low_memory=False)
        shared_sqtl = pd.read_csv(cache["sqtl"], sep="\t", compression="gzip", low_memory=False)

        eqtl_raw = shared_eqtl[shared_eqtl["GTEX_VARIANT_ID"].astype(str).isin(study_ids)].copy()
        sqtl_raw = shared_sqtl[shared_sqtl["GTEX_VARIANT_ID"].astype(str).isin(study_ids)].copy()

        eqtl = add_variant_context(eqtl_raw, variants)
        sqtl = add_variant_context(sqtl_raw, variants)

        eqtl.to_csv(eqtl_output, sep="\t", index=False, compression="gzip")
        sqtl.to_csv(sqtl_output, sep="\t", index=False, compression="gzip")

        gene_evidence = make_variant_gene_evidence(eqtl, sqtl)
        gene_evidence.to_csv(gene_output, sep="\t", index=False, compression="gzip")

        variant_summary = build_variant_summary(variants, eqtl, sqtl)
        variant_summary.to_csv(variant_output, sep="\t", index=False)

        locus_summary = build_locus_summary(variant_summary)
        locus_summary.to_csv(locus_output, sep="\t", index=False)

        n_total = int(len(variant_summary))
        n_eqtl = int(variant_summary["HAS_GTEX_EQTL"].sum())
        n_sqtl = int(variant_summary["HAS_GTEX_SQTL"].sum())
        n_both = int(variant_summary["HAS_GTEX_EQTL_AND_SQTL"].sum())
        n_any = int(variant_summary["HAS_GTEX_EQTL_OR_SQTL"].sum())
        n_none = int(n_total - n_any)

        summary = {
            "STEP08_VERSION": STEP08_VERSION,
            "QTL_TASK_ID": task_id,
            "STUDY_ACCESSION": accession,
            "PHENOTYPE": phenotype,
            "ANCESTRY_CODE": ancestry_code,
            "ANCESTRY_LABEL": ancestry_label,
            "GTEX_RELEASE": "v11",
            "GENOME_BUILD": "GRCh38",
            "TISSUE_POLICY": "ALL_GTEX_V11_TISSUES",
            "N_INPUT_VARIANTS": n_total,
            "N_EQTL_VARIANTS": n_eqtl,
            "N_SQTL_VARIANTS": n_sqtl,
            "N_EQTL_AND_SQTL_VARIANTS": n_both,
            "N_ANY_QTL_VARIANTS": n_any,
            "N_NO_SIGNIFICANT_QTL_VARIANTS": n_none,
            "N_EQTL_ASSOCIATIONS": int(len(eqtl)),
            "N_SQTL_ASSOCIATIONS": int(len(sqtl)),
            "N_VARIANT_GENE_EVIDENCE_ROWS": int(len(gene_evidence)),
            "N_LOCI": int(variant_summary["LOCUS_ID"].nunique()),
            "N_EQTL_TISSUES_WITH_MATCHES": int(eqtl["GTEX_TISSUE"].nunique()) if not eqtl.empty else 0,
            "N_SQTL_TISSUES_WITH_MATCHES": int(sqtl["GTEX_TISSUE"].nunique()) if not sqtl.empty else 0,
            "VARIANT_MAPPING_FILE": str(mapping_output),
            "EQTL_FILE": str(eqtl_output),
            "SQTL_FILE": str(sqtl_output),
            "VARIANT_GENE_EVIDENCE_FILE": str(gene_output),
            "VARIANT_SUMMARY_FILE": str(variant_output),
            "LOCUS_SUMMARY_FILE": str(locus_output),
            "STATUS": "COMPLETE",
            "COMPLETED_UTC": datetime.now(timezone.utc).isoformat(),
        }
        write_json(summary_output, summary)

        if failed_output.exists():
            failed_output.unlink()

        banner("STEP 08 COMPLETE")
        print(f"Study                     : {accession}")
        print(f"Input variants            : {n_total:,}")
        print(f"eQTL variants             : {n_eqtl:,}")
        print(f"sQTL variants             : {n_sqtl:,}")
        print(f"Both eQTL + sQTL          : {n_both:,}")
        print(f"Any significant GTEx QTL  : {n_any:,}")
        print(f"No significant GTEx QTL   : {n_none:,}")
        print(f"eQTL associations         : {len(eqtl):,}")
        print(f"sQTL associations         : {len(sqtl):,}")
        print(f"Loci                      : {variant_summary['LOCUS_ID'].nunique():,}")
        print(f"Main table                : {variant_output}")

    except Exception as error:
        failure_text = (
            "STEP 08 GTEx QTL INTEGRATION FAILED\n\n"
            f"Task ID: {task_id}\n"
            f"Accession: {accession}\n"
            f"Phenotype: {phenotype}\n"
            f"Ancestry: {ancestry_label} ({ancestry_code})\n"
            f"Input: {input_file}\n\n"
            f"Error:\n{type(error).__name__}: {error}\n\n"
            f"{traceback.format_exc()}"
        )
        failed_output.write_text(failure_text, encoding="utf-8")
        print(failure_text, file=sys.stderr)
        raise


