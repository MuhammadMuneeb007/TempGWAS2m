def normalize_qtl_hits(
    raw: pd.DataFrame,
    qtl_type: str,
    tissue: str,
    source_file: Path,
) -> pd.DataFrame:
    if raw.empty:
        return pd.DataFrame(
            columns=[
                "GTEX_VARIANT_ID",
                "QTL_TYPE",
                "GTEX_TISSUE",
                "GTEX_GENE_ID",
                "GTEX_PHENOTYPE_ID",
                "GTEX_PVALUE",
                "GTEX_NES",
                "GTEX_SLOPE_SE",
                "GTEX_MAF",
                "SOURCE_FILE",
            ]
        )

    variant_col = first_existing(raw.columns, ["variant_id", "variantId", "variant"])
    if variant_col is None:
        return pd.DataFrame()

    gene_col = first_existing(
        raw.columns,
        ["gene_id", "geneId", "gencodeId", "gencode_id", "gene"],
    )
    phenotype_col = first_existing(
        raw.columns,
        ["phenotype_id", "phenotypeId", "phenotype", "intron_id", "cluster_id"],
    )
    p_col = first_existing(
        raw.columns,
        ["pval_nominal", "p_value", "pvalue", "pval", "pValue"],
    )
    nes_col = first_existing(
        raw.columns,
        ["slope", "nes", "NES", "beta", "effect_size"],
    )
    se_col = first_existing(
        raw.columns,
        ["slope_se", "se", "standard_error", "beta_se"],
    )
    maf_col = first_existing(raw.columns, ["maf", "MAF", "minor_allele_frequency"])

    out = pd.DataFrame()
    out["GTEX_VARIANT_ID"] = raw[variant_col].astype(str)
    out["QTL_TYPE"] = qtl_type
    out["GTEX_TISSUE"] = tissue
    out["GTEX_GENE_ID"] = raw[gene_col].astype(str) if gene_col else np.nan
    out["GTEX_PHENOTYPE_ID"] = raw[phenotype_col].astype(str) if phenotype_col else np.nan
    out["GTEX_PVALUE"] = pd.to_numeric(raw[p_col], errors="coerce") if p_col else np.nan
    out["GTEX_NES"] = pd.to_numeric(raw[nes_col], errors="coerce") if nes_col else np.nan
    out["GTEX_SLOPE_SE"] = pd.to_numeric(raw[se_col], errors="coerce") if se_col else np.nan
    out["GTEX_MAF"] = pd.to_numeric(raw[maf_col], errors="coerce") if maf_col else np.nan
    out["SOURCE_FILE"] = str(source_file)

    # Keep raw IDs clean rather than literal 'nan'.
    for col in ["GTEX_GENE_ID", "GTEX_PHENOTYPE_ID"]:
        out[col] = out[col].replace({"nan": np.nan, "None": np.nan, "": np.nan})

    return out


def scan_qtl_files(
    files: list[Path],
    qtl_type: str,
    target_variant_ids: set[str],
    chunk_size: int,
) -> tuple[pd.DataFrame, list[dict]]:
    matches = []
    audit = []

    for number, path in enumerate(files, start=1):
        tissue = tissue_from_filename(path)
        n_rows = 0
        n_hits = 0
        status = "OK"
        error_text = ""

        print(
            f"[{qtl_type}] {number:>3}/{len(files):<3} "
            f"{tissue:<40} {path.name}",
            flush=True,
        )

        try:
            header = pd.read_csv(path, sep="\t", nrows=0, compression="infer")
            variant_col = first_existing(
                header.columns,
                ["variant_id", "variantId", "variant"],
            )
            if variant_col is None:
                status = "SKIPPED_NO_VARIANT_ID"
            else:
                iterator = pd.read_csv(
                    path,
                    sep="\t",
                    chunksize=chunk_size,
                    compression="infer",
                    low_memory=False,
                )
                for chunk in iterator:
                    n_rows += len(chunk)
                    ids = chunk[variant_col].astype(str)
                    hit = chunk.loc[ids.isin(target_variant_ids)].copy()
                    if hit.empty:
                        continue
                    n_hits += len(hit)
                    normalized = normalize_qtl_hits(
                        hit,
                        qtl_type=qtl_type,
                        tissue=tissue,
                        source_file=path,
                    )
                    if not normalized.empty:
                        matches.append(normalized)
        except Exception as error:
            status = "ERROR"
            error_text = f"{type(error).__name__}: {error}"

        audit.append(
            {
                "QTL_TYPE": qtl_type,
                "TISSUE": tissue,
                "SOURCE_FILE": str(path),
                "N_ROWS_SCANNED": n_rows,
                "N_TARGET_MATCH_ROWS": n_hits,
                "STATUS": status,
                "ERROR": error_text,
            }
        )

    if matches:
        combined = pd.concat(matches, ignore_index=True)
        subset = [
            c
            for c in [
                "GTEX_VARIANT_ID",
                "QTL_TYPE",
                "GTEX_TISSUE",
                "GTEX_GENE_ID",
                "GTEX_PHENOTYPE_ID",
            ]
            if c in combined.columns
        ]
        combined = combined.drop_duplicates(subset=subset, keep="first")
    else:
        combined = pd.DataFrame(
            columns=[
                "GTEX_VARIANT_ID",
                "QTL_TYPE",
                "GTEX_TISSUE",
                "GTEX_GENE_ID",
                "GTEX_PHENOTYPE_ID",
                "GTEX_PVALUE",
                "GTEX_NES",
                "GTEX_SLOPE_SE",
                "GTEX_MAF",
                "SOURCE_FILE",
            ]
        )

    return combined, audit


