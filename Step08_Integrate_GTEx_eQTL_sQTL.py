def planner_mode(args) -> None:
    validate_arguments(args)

    root = Path.cwd().resolve()
    phenotype = args.phenotype.strip()
    phenotype_slug = slugify(phenotype)
    ancestry_code, ancestry_label = canonical_ancestry(args.ancestry)
    ancestry_slug = slugify(ancestry_label)

    pipeline_python = root / "envs" / "pipeline" / "bin" / "python"
    if not pipeline_python.exists():
        pipeline_python = Path(sys.executable).resolve()

    gtex_root = resolve_gtex_root(root, args.gtex_root)
    eqtl_root = gtex_root / "qtl" / "eQTL"
    sqtl_root = gtex_root / "qtl" / "sQTL"
    lookup_file = (
        gtex_root
        / "reference"
        / "GTEx_Analysis_2021-02-11_v11_WholeGenomeSeq_953Indiv.lookup_table.txt.gz"
    )

    eqtl_files = discover_significant_pair_files(eqtl_root, "EQTL")
    sqtl_files = discover_significant_pair_files(sqtl_root, "SQTL")

    if not eqtl_files:
        raise FileNotFoundError(
            f"No GTEx v11 eQTL significant-pair files found under:\n  {eqtl_root}"
        )
    if not sqtl_files:
        raise FileNotFoundError(
            f"No GTEx v11 sQTL significant-pair files found under:\n  {sqtl_root}"
        )

    annotation_root = root / "07_annotation" / phenotype_slug / ancestry_slug
    if not annotation_root.exists():
        raise FileNotFoundError(
            f"Step07 annotation directory does not exist:\n  {annotation_root}"
        )

    qtl_root = root / "08_qtl" / phenotype_slug / ancestry_slug
    log_root = root / "logs" / "step08_qtl" / phenotype_slug / ancestry_slug
    qtl_root.mkdir(parents=True, exist_ok=True)
    log_root.mkdir(parents=True, exist_ok=True)

    rows = []
    excluded = []

    for study_dir in sorted(annotation_root.glob("GCST*")):
        if not study_dir.is_dir():
            continue
        accession = study_dir.name
        summary_file = study_dir / "annotation_summary.json"
        summary = safe_read_json(summary_file)
        variant_file = study_dir / f"{accession}_VEP_variant_summary.tsv"

        reason = ""
        if not summary:
            reason = "Step07 annotation summary missing/unreadable"
        elif str(summary.get("STATUS", "")).upper() != "COMPLETE":
            reason = f"Step07 status is {summary.get('STATUS', 'UNKNOWN')}"
        elif not variant_file.exists() or variant_file.stat().st_size == 0:
            reason = "Step07 variant summary missing/empty"

        if reason:
            excluded.append(
                {
                    "STUDY_ACCESSION": accession,
                    "STEP07_STATUS": summary.get("STATUS", ""),
                    "REASON": reason,
                }
            )
            continue

        rows.append(
            {
                "QTL_TASK_ID": len(rows) + 1,
                "STUDY_ACCESSION": accession,
                "PHENOTYPE": phenotype,
                "ANCESTRY_CODE": ancestry_code,
                "ANCESTRY_LABEL": ancestry_label,
                "STEP07_VARIANT_FILE": str(variant_file.resolve()),
                "STEP07_SUMMARY_FILE": str(summary_file.resolve()),
                "OUTPUT_DIR": str((qtl_root / accession).resolve()),
                "GTEX_ROOT": str(gtex_root.resolve()),
                "GTEX_EQTL_ROOT": str(eqtl_root.resolve()),
                "GTEX_SQTL_ROOT": str(sqtl_root.resolve()),
                "GTEX_LOOKUP_FILE": str(lookup_file.resolve()),
                "CHUNK_SIZE": int(args.chunk_size),
                "FORCE": bool(args.force),
                "REBUILD_CACHE": bool(args.rebuild_cache),
                "STEP08_VERSION": STEP08_VERSION,
            }
        )

    excluded_file = qtl_root / "qtl_excluded_studies.tsv"
    pd.DataFrame(
        excluded,
        columns=["STUDY_ACCESSION", "STEP07_STATUS", "REASON"],
    ).to_csv(excluded_file, sep="\t", index=False)

    if not rows:
        raise RuntimeError(
            "No completed Step07 studies are currently eligible for Step08.\n"
            f"Inspect:\n  {excluded_file}"
        )

    manifest = pd.DataFrame(rows)
    manifest_file = (qtl_root / "qtl_manifest.tsv").resolve()
    manifest.to_csv(manifest_file, sep="\t", index=False)

    bash_file = root / f"Step08_GTEx_QTL_{phenotype_slug}_{ancestry_slug}.sh"
    script_path = Path(__file__).resolve()
    array_spec = f"1-{len(manifest)}%{args.max_parallel}"
    job_name = f"GTEx_{phenotype_slug}_{ancestry_code.lower()}"[:100]

    bash_text = f'''#!/bin/bash
#SBATCH --job-name={job_name}
#SBATCH --nodes=1
#SBATCH --partition={args.partition}
#SBATCH --time={args.time}
#SBATCH --output={log_root}/qtl.%A_%a.out
#SBATCH --error={log_root}/qtl.%A_%a.err
#SBATCH --array={array_spec}
#SBATCH --mem={args.memory}
#SBATCH --cpus-per-task={args.cpus}
#SBATCH --ntasks=1

set -euo pipefail

cd {shlex.quote(str(root))}

export GWAS_QTL_MANIFEST={shlex.quote(str(manifest_file))}

printf '%s\n' '=============================================================='
printf '%s\n' 'STEP 08 - GTEx v11 ALL-TISSUE eQTL + sQTL'
printf '%s\n' '=============================================================='
printf 'Job ID        : %s\n' "$SLURM_JOB_ID"
printf 'Array task ID : %s\n' "$SLURM_ARRAY_TASK_ID"
printf 'Phenotype     : %s\n' {shlex.quote(phenotype)}
printf 'Ancestry      : %s (%s)\n' {shlex.quote(ancestry_label)} {shlex.quote(ancestry_code)}
printf 'GTEx root     : %s\n' {shlex.quote(str(gtex_root))}
printf 'Mode          : ALL TISSUES\n'
printf 'Hostname      : %s\n' "$(hostname)"
printf '%s\n' '=============================================================='

{shlex.quote(str(pipeline_python))} {shlex.quote(str(script_path))}

printf '%s\n' '=============================================================='
printf 'STEP 08 TASK COMPLETE: %s\n' "$SLURM_ARRAY_TASK_ID"
printf '%s\n' '=============================================================='
'''
    bash_file.write_text(bash_text, encoding="utf-8")
    bash_file.chmod(0o755)

    banner("STEP 08 - GTEx v11 ALL-TISSUE QTL PLANNER")
    print(f"Phenotype          : {phenotype}")
    print(f"Ancestry           : {ancestry_label} ({ancestry_code})")
    print(f"Eligible studies   : {len(manifest)}")
    print(f"Excluded studies   : {len(excluded)}")
    print(f"GTEx root          : {gtex_root}")
    print(f"eQTL files         : {len(eqtl_files)}")
    print(f"sQTL files         : {len(sqtl_files)}")
    print(f"Lookup table       : {lookup_file if lookup_file.exists() else 'MISSING - constructed IDs will be used'}")
    print("Tissue policy      : ALL GTEx tissues (no phenotype-specific filtering)")
    print(f"Chunk size         : {args.chunk_size:,}")
    print(f"Array              : {array_spec}")
    print()
    print(
        manifest[["QTL_TASK_ID", "STUDY_ACCESSION", "STEP07_VARIANT_FILE"]]
        .to_string(index=False)
    )
    print()
    print(f"Manifest:\n  {manifest_file}")
    print(f"Excluded:\n  {excluded_file}")
    print(f"Generated SLURM:\n  {bash_file}")
    print()
    print("NEXT COMMAND:")
    print()
    print(f"  sbatch {bash_file.name}")
    print()


