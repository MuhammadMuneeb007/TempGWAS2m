def shared_paths(qtl_root: Path) -> dict[str, Path]:
    shared = qtl_root / "shared"
    shared.mkdir(parents=True, exist_ok=True)
    return {
        "dir": shared,
        "lock": shared / ".GTEx_v11_cache.lock",
        "targets": shared / "GTEx_v11_target_variants.tsv.gz",
        "mapping": shared / "GTEx_v11_variant_mapping.tsv.gz",
        "eqtl": shared / "GTEx_v11_eQTL_target_matches.tsv.gz",
        "sqtl": shared / "GTEx_v11_sQTL_target_matches.tsv.gz",
        "audit": shared / "GTEx_v11_files_scanned.tsv",
        "summary": shared / "GTEx_v11_cache_summary.json",
        "complete": shared / "GTEx_v11_cache.complete",
    }


def collect_union_targets(manifest: pd.DataFrame) -> pd.DataFrame:
    frames = []
    for _, row in manifest.iterrows():
        accession = str(row["STUDY_ACCESSION"])
        path = Path(row["STEP07_VARIANT_FILE"]).resolve()
        variants = load_step07_variants(path)
        variants["STUDY_ACCESSION"] = accession
        frames.append(
            variants[
                [
                    "STUDY_ACCESSION",
                    "VEP_ID",
                    "CHR",
                    "REFERENCE_POS",
                    "REFERENCE_REF",
                    "REFERENCE_ALT",
                    "GTEX_CONSTRUCTED_VARIANT_ID",
                    "GTEX_MATCH_KEY",
                ]
            ]
        )
    union = pd.concat(frames, ignore_index=True)
    return union.drop_duplicates(
        subset=["GTEX_MATCH_KEY"],
        keep="first",
    ).reset_index(drop=True)


def cache_is_current(
    paths: dict[str, Path],
    target_hash: str,
    resource_hash: str,
) -> bool:
    if not paths["complete"].exists():
        return False
    required = [paths["targets"], paths["mapping"], paths["eqtl"], paths["sqtl"], paths["summary"]]
    if not all(p.exists() and p.stat().st_size > 0 for p in required):
        return False
    summary = safe_read_json(paths["summary"])
    return (
        summary.get("STEP08_VERSION") == STEP08_VERSION
        and summary.get("TARGET_HASH") == target_hash
        and summary.get("RESOURCE_HASH") == resource_hash
        and summary.get("TISSUE_POLICY") == "ALL_GTEX_V11_TISSUES"
    )


def ensure_shared_cache(
    manifest: pd.DataFrame,
    qtl_root: Path,
    force_rebuild: bool,
) -> dict[str, Path]:
    paths = shared_paths(qtl_root)

    gtex_root = Path(manifest.iloc[0]["GTEX_ROOT"]).resolve()
    eqtl_root = Path(manifest.iloc[0]["GTEX_EQTL_ROOT"]).resolve()
    sqtl_root = Path(manifest.iloc[0]["GTEX_SQTL_ROOT"]).resolve()
    lookup_file = Path(manifest.iloc[0]["GTEX_LOOKUP_FILE"]).resolve()
    chunk_size = int(manifest.iloc[0]["CHUNK_SIZE"])

    eqtl_files = discover_significant_pair_files(eqtl_root, "EQTL")
    sqtl_files = discover_significant_pair_files(sqtl_root, "SQTL")
    if not eqtl_files or not sqtl_files:
        raise RuntimeError(
            "GTEx significant-pair files disappeared after planning. "
            f"eQTL={len(eqtl_files)}, sQTL={len(sqtl_files)}"
        )

    union = collect_union_targets(manifest)
    target_hash = sha256_strings(union["GTEX_MATCH_KEY"].tolist())
    resource_hash = resource_signature(eqtl_files + sqtl_files + ([lookup_file] if lookup_file.exists() else []))

    with open(paths["lock"], "w", encoding="utf-8") as lock_handle:
        print("Waiting for shared GTEx cache lock if another task is building it...", flush=True)
        fcntl.flock(lock_handle.fileno(), fcntl.LOCK_EX)

        if not force_rebuild and cache_is_current(paths, target_hash, resource_hash):
            print("Shared GTEx v11 cache is current; reusing it.")
            return paths

        banner("BUILDING SHARED GTEx v11 ALL-TISSUE CACHE")
        print(f"Target variants      : {len(union):,}")
        print(f"eQTL tissue files    : {len(eqtl_files):,}")
        print(f"sQTL tissue files    : {len(sqtl_files):,}")
        print(f"GTEx root            : {gtex_root}")
        print("Tissue policy        : ALL GTEx v11 tissues")

        for key in ["complete", "targets", "mapping", "eqtl", "sqtl", "audit", "summary"]:
            p = paths[key]
            if p.exists():
                p.unlink()

        union.to_csv(paths["targets"], sep="\t", index=False, compression="gzip")

        mapping = map_targets_with_lookup(union, lookup_file, chunk_size)
        mapping.to_csv(paths["mapping"], sep="\t", index=False, compression="gzip")

        target_ids = set(mapping["GTEX_VARIANT_ID"].dropna().astype(str))
        target_ids.update(mapping["GTEX_CONSTRUCTED_VARIANT_ID"].dropna().astype(str))

        banner("SCANNING ALL GTEx v11 eQTL TISSUES")
        eqtl, audit_eqtl = scan_qtl_files(
            eqtl_files,
            qtl_type="EQTL",
            target_variant_ids=target_ids,
            chunk_size=chunk_size,
        )
        eqtl.to_csv(paths["eqtl"], sep="\t", index=False, compression="gzip")

        banner("SCANNING ALL GTEx v11 sQTL TISSUES")
        sqtl, audit_sqtl = scan_qtl_files(
            sqtl_files,
            qtl_type="SQTL",
            target_variant_ids=target_ids,
            chunk_size=chunk_size,
        )
        sqtl.to_csv(paths["sqtl"], sep="\t", index=False, compression="gzip")

        audit = pd.DataFrame(audit_eqtl + audit_sqtl)
        audit.to_csv(paths["audit"], sep="\t", index=False)

        summary = {
            "STEP08_VERSION": STEP08_VERSION,
            "GTEX_RELEASE": "v11",
            "GENOME_BUILD": "GRCh38",
            "TISSUE_POLICY": "ALL_GTEX_V11_TISSUES",
            "GTEX_ROOT": str(gtex_root),
            "N_TARGET_VARIANTS": int(len(union)),
            "N_EQTL_FILES": int(len(eqtl_files)),
            "N_SQTL_FILES": int(len(sqtl_files)),
            "N_EQTL_MATCH_ROWS": int(len(eqtl)),
            "N_SQTL_MATCH_ROWS": int(len(sqtl)),
            "N_EQTL_TARGET_VARIANTS": int(eqtl["GTEX_VARIANT_ID"].nunique()) if not eqtl.empty else 0,
            "N_SQTL_TARGET_VARIANTS": int(sqtl["GTEX_VARIANT_ID"].nunique()) if not sqtl.empty else 0,
            "TARGET_HASH": target_hash,
            "RESOURCE_HASH": resource_hash,
            "BUILT_UTC": datetime.now(timezone.utc).isoformat(),
        }
        write_json(paths["summary"], summary)
        paths["complete"].write_text("complete\n", encoding="utf-8")

        banner("SHARED GTEx CACHE COMPLETE")
        print(f"eQTL matched rows : {len(eqtl):,}")
        print(f"sQTL matched rows : {len(sqtl):,}")

    return paths


