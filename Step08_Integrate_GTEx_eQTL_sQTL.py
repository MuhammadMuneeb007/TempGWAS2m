def add_variant_context(qtl: pd.DataFrame, variants: pd.DataFrame) -> pd.DataFrame:
    if qtl.empty:
        return qtl.copy()

    # Allow matching by the exact lookup ID or the deterministic constructed ID.
    id_to_vep = {}
    for _, row in variants.iterrows():
        seen_ids = set()
        for col in ["GTEX_VARIANT_ID", "GTEX_CONSTRUCTED_VARIANT_ID"]:
            value = row.get(col)
            if pd.isna(value) or not str(value):
                continue
            value = str(value)
            if value in seen_ids:
                continue
            seen_ids.add(value)
            bucket = id_to_vep.setdefault(value, [])
            if not any(str(existing.get("VEP_ID")) == str(row.get("VEP_ID")) for existing in bucket):
                bucket.append(row)

    output_rows = []
    for _, qrow in qtl.iterrows():
        variant_id = str(qrow["GTEX_VARIANT_ID"])
        contexts = id_to_vep.get(variant_id, [])
        for context in contexts:
            record = context.to_dict()
            record.update(qrow.to_dict())
            output_rows.append(record)

    return pd.DataFrame(output_rows)


def make_variant_gene_evidence(eqtl: pd.DataFrame, sqtl: pd.DataFrame) -> pd.DataFrame:
    frames = [x for x in [eqtl, sqtl] if x is not None and not x.empty]
    if not frames:
        return pd.DataFrame(
            columns=[
                "VEP_ID",
                "LOCUS_ID",
                "GTEX_GENE_ID",
                "GTEX_PHENOTYPE_ID",
                "HAS_EQTL",
                "HAS_SQTL",
                "QTL_TYPES",
                "TISSUES",
                "N_TISSUES",
                "MIN_QTL_P",
                "MAX_ABS_NES",
                "N_EQTL_ASSOCIATIONS",
                "N_SQTL_ASSOCIATIONS",
                "MIN_EQTL_P",
                "MIN_SQTL_P",
                "PIP",
            ]
        )

    qtl = pd.concat(frames, ignore_index=True)
    gene_key = qtl["GTEX_GENE_ID"].fillna("").astype(str)
    phenotype_key = qtl["GTEX_PHENOTYPE_ID"].fillna("").astype(str)
    qtl["QTL_TARGET_KEY"] = np.where(gene_key != "", gene_key, phenotype_key)

    rows = []
    for (vep_id, locus_id, target), group in qtl.groupby(
        ["VEP_ID", "LOCUS_ID", "QTL_TARGET_KEY"],
        dropna=False,
    ):
        eq = group[group["QTL_TYPE"] == "EQTL"]
        sq = group[group["QTL_TYPE"] == "SQTL"]
        rows.append(
            {
                "VEP_ID": vep_id,
                "LOCUS_ID": locus_id,
                "QTL_TARGET_KEY": target,
                "GTEX_GENE_ID": collapse(group["GTEX_GENE_ID"]),
                "GTEX_PHENOTYPE_ID": collapse(group["GTEX_PHENOTYPE_ID"]),
                "HAS_EQTL": not eq.empty,
                "HAS_SQTL": not sq.empty,
                "QTL_TYPES": collapse(group["QTL_TYPE"]),
                "TISSUES": collapse(group["GTEX_TISSUE"]),
                "N_TISSUES": int(group["GTEX_TISSUE"].nunique()),
                "MIN_QTL_P": safe_numeric_min(group["GTEX_PVALUE"]),
                "MAX_ABS_NES": safe_numeric_max_abs(group["GTEX_NES"]),
                "N_EQTL_ASSOCIATIONS": int(len(eq)),
                "N_SQTL_ASSOCIATIONS": int(len(sq)),
                "MIN_EQTL_P": safe_numeric_min(eq["GTEX_PVALUE"]) if not eq.empty else np.nan,
                "MIN_SQTL_P": safe_numeric_min(sq["GTEX_PVALUE"]) if not sq.empty else np.nan,
                "PIP": pd.to_numeric(group["PIP"], errors="coerce").max(),
            }
        )

    output = pd.DataFrame(rows)
    if not output.empty:
        output = output.sort_values(
            ["LOCUS_ID", "PIP", "MIN_QTL_P"],
            ascending=[True, False, True],
            kind="stable",
        )
    return output


def top_qtl_record(group: pd.DataFrame) -> dict:
    if group.empty:
        return {}
    p = pd.to_numeric(group["GTEX_PVALUE"], errors="coerce")
    if p.notna().any():
        return group.loc[p.idxmin()].to_dict()
    return group.iloc[0].to_dict()


def build_variant_summary(variants: pd.DataFrame, eqtl: pd.DataFrame, sqtl: pd.DataFrame) -> pd.DataFrame:
    frames = [x for x in [eqtl, sqtl] if x is not None and not x.empty]
    if frames:
        all_qtl = pd.concat(frames, ignore_index=True)
        grouped = {key: group for key, group in all_qtl.groupby("VEP_ID")}
    else:
        grouped = {}

    rows = []
    for _, variant in variants.iterrows():
        vep_id = variant["VEP_ID"]
        group = grouped.get(vep_id, pd.DataFrame())
        if group.empty:
            eq = pd.DataFrame()
            sq = pd.DataFrame()
        else:
            eq = group[group["QTL_TYPE"] == "EQTL"]
            sq = group[group["QTL_TYPE"] == "SQTL"]

        record = variant.to_dict()
        record["HAS_GTEX_EQTL"] = not eq.empty
        record["N_GTEX_EQTL_ASSOCIATIONS"] = int(len(eq))
        record["N_GTEX_EQTL_TISSUES"] = int(eq["GTEX_TISSUE"].nunique()) if not eq.empty else 0
        record["GTEX_EQTL_TISSUES"] = collapse(eq["GTEX_TISSUE"]) if not eq.empty else ""
        record["GTEX_EQTL_GENES"] = collapse(eq["GTEX_GENE_ID"]) if not eq.empty else ""
        record["MIN_GTEX_EQTL_P"] = safe_numeric_min(eq["GTEX_PVALUE"]) if not eq.empty else np.nan
        record["MAX_ABS_GTEX_EQTL_NES"] = safe_numeric_max_abs(eq["GTEX_NES"]) if not eq.empty else np.nan

        record["HAS_GTEX_SQTL"] = not sq.empty
        record["N_GTEX_SQTL_ASSOCIATIONS"] = int(len(sq))
        record["N_GTEX_SQTL_TISSUES"] = int(sq["GTEX_TISSUE"].nunique()) if not sq.empty else 0
        record["GTEX_SQTL_TISSUES"] = collapse(sq["GTEX_TISSUE"]) if not sq.empty else ""
        record["GTEX_SQTL_GENES"] = collapse(sq["GTEX_GENE_ID"]) if not sq.empty else ""
        record["GTEX_SQTL_PHENOTYPES"] = collapse(sq["GTEX_PHENOTYPE_ID"]) if not sq.empty else ""
        record["MIN_GTEX_SQTL_P"] = safe_numeric_min(sq["GTEX_PVALUE"]) if not sq.empty else np.nan
        record["MAX_ABS_GTEX_SQTL_NES"] = safe_numeric_max_abs(sq["GTEX_NES"]) if not sq.empty else np.nan

        record["HAS_GTEX_EQTL_OR_SQTL"] = (not eq.empty) or (not sq.empty)
        record["HAS_GTEX_EQTL_AND_SQTL"] = (not eq.empty) and (not sq.empty)

        top_eq = top_qtl_record(eq)
        top_sq = top_qtl_record(sq)
        record["TOP_EQTL_TISSUE"] = top_eq.get("GTEX_TISSUE", "")
        record["TOP_EQTL_GENE"] = top_eq.get("GTEX_GENE_ID", "")
        record["TOP_EQTL_P"] = top_eq.get("GTEX_PVALUE", np.nan)
        record["TOP_EQTL_NES"] = top_eq.get("GTEX_NES", np.nan)
        record["TOP_SQTL_TISSUE"] = top_sq.get("GTEX_TISSUE", "")
        record["TOP_SQTL_GENE"] = top_sq.get("GTEX_GENE_ID", "")
        record["TOP_SQTL_PHENOTYPE"] = top_sq.get("GTEX_PHENOTYPE_ID", "")
        record["TOP_SQTL_P"] = top_sq.get("GTEX_PVALUE", np.nan)
        record["TOP_SQTL_NES"] = top_sq.get("GTEX_NES", np.nan)
        rows.append(record)

    return pd.DataFrame(rows)


def build_locus_summary(summary: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for locus, group in summary.groupby("LOCUS_ID", dropna=False):
        eq = group[group["HAS_GTEX_EQTL"]]
        sq = group[group["HAS_GTEX_SQTL"]]
        any_qtl = group[group["HAS_GTEX_EQTL_OR_SQTL"]]
        rows.append(
            {
                "LOCUS_ID": locus,
                "N_VARIANTS": int(len(group)),
                "MAX_PIP": pd.to_numeric(group["PIP"], errors="coerce").max(),
                "N_EQTL_VARIANTS": int(len(eq)),
                "N_SQTL_VARIANTS": int(len(sq)),
                "N_ANY_QTL_VARIANTS": int(len(any_qtl)),
                "N_EQTL_AND_SQTL_VARIANTS": int(group["HAS_GTEX_EQTL_AND_SQTL"].sum()),
                "EQTL_TISSUES": collapse(eq["GTEX_EQTL_TISSUES"]) if not eq.empty else "",
                "SQTL_TISSUES": collapse(sq["GTEX_SQTL_TISSUES"]) if not sq.empty else "",
                "EQTL_GENES": collapse(eq["GTEX_EQTL_GENES"]) if not eq.empty else "",
                "SQTL_GENES": collapse(sq["GTEX_SQTL_GENES"]) if not sq.empty else "",
                "MIN_EQTL_P": safe_numeric_min(eq["MIN_GTEX_EQTL_P"]) if not eq.empty else np.nan,
                "MIN_SQTL_P": safe_numeric_min(sq["MIN_GTEX_SQTL_P"]) if not sq.empty else np.nan,
            }
        )
    return pd.DataFrame(rows)


