"""
Generic GWAS Pipeline
STEP 08 - GTEx v11 eQTL + sQTL integration (ALL tissues)

This step is phenotype-agnostic. It never chooses tissues from the phenotype.
Every eligible study is scanned against ALL locally available GTEx v11
single-tissue significant eQTL and sQTL association files.

MODES
=====

1) Planner

    python Step08_Integrate_GTEx_eQTL_sQTL.py \
        --phenotype migraine \
        --ancestry EUR

Creates:
    08_qtl/<phenotype>/<ancestry>/qtl_manifest.tsv
    Step08_GTEx_QTL_<phenotype>_<ancestry>.sh

2) Direct one-index execution

    python Step08_Integrate_GTEx_eQTL_sQTL.py \
        --phenotype migraine \
        --ancestry EUR \
        --index 1

3) SLURM-array worker

The generated bash exports:
    SLURM_ARRAY_TASK_ID
    GWAS_QTL_MANIFEST

SCIENTIFIC INPUT
================

Step 07 per-study main table:
    07_annotation/<phenotype>/<ancestry>/<GCST>/
        <GCST>_VEP_variant_summary.tsv

LOCAL GTEx v11 RESOURCES
========================

The script expects the resources generated by Step00_Check_Resources.py:

    resources/gtex/v11/qtl/eQTL/
    resources/gtex/v11/qtl/sQTL/
    resources/gtex/v11/reference/
      GTEx_Analysis_2021-02-11_v11_WholeGenomeSeq_953Indiv.lookup_table.txt.gz

It scans all significant-pair files discovered below eQTL and sQTL.
No GTEx API and no phenotype-specific tissue list are used.

SHARED CACHE
============

To avoid rescanning the multi-GB GTEx files once per GWAS, the first worker
builds a shared cache from the UNION of all Step-07 variants in the manifest.
An fcntl file lock prevents two SLURM tasks from building it simultaneously.
Other workers reuse the completed cache.

OUTPUT
======

08_qtl/<phenotype>/<ancestry>/
    qtl_manifest.tsv
    qtl_excluded_studies.tsv

    shared/
        GTEx_v11_target_variants.tsv.gz
        GTEx_v11_variant_mapping.tsv.gz
        GTEx_v11_eQTL_target_matches.tsv.gz
        GTEx_v11_sQTL_target_matches.tsv.gz
        GTEx_v11_files_scanned.tsv
        GTEx_v11_cache_summary.json
        GTEx_v11_cache.complete

    <GCST>/
        <GCST>_GTEx_variant_mapping.tsv
        <GCST>_GTEx_eQTL.tsv.gz
        <GCST>_GTEx_sQTL.tsv.gz
        <GCST>_GTEx_variant_gene_evidence.tsv.gz
        <GCST>_GTEx_QTL_variant_summary.tsv
        <GCST>_GTEx_QTL_locus_summary.tsv
        qtl_summary.json
        QTL_FAILED.txt   # hard failure only

INTERPRETATION
==============

HAS_GTEX_EQTL=False or HAS_GTEX_SQTL=False means that no significant
association was found in the local GTEx v11 significant-pair resources.
It does NOT prove absence of a regulatory effect.
"""

