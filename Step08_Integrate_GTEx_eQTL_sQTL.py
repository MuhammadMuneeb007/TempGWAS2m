# DIRECT INDEX MODE
# =============================================================================

def direct_index_mode(args) -> None:
    validate_arguments(args)
    root = Path.cwd().resolve()
    phenotype = args.phenotype.strip()
    phenotype_slug = slugify(phenotype)
    ancestry_code, ancestry_label = canonical_ancestry(args.ancestry)
    ancestry_slug = slugify(ancestry_label)

    manifest_file = (
        root / "08_qtl" / phenotype_slug / ancestry_slug / "qtl_manifest.tsv"
    ).resolve()

    if not manifest_file.exists():
        raise FileNotFoundError(
            "Step08 manifest does not exist. Run the planner once without --index first:\n\n"
            f"  python {Path(__file__).name} --phenotype {shlex.quote(phenotype)} "
            f"--ancestry {shlex.quote(ancestry_code)}"
        )

    manifest = pd.read_csv(manifest_file, sep="\t", dtype=str, low_memory=False)
    if "QTL_TASK_ID" not in manifest.columns:
        raise RuntimeError("Step08 manifest has no QTL_TASK_ID column")
    task_numbers = pd.to_numeric(manifest["QTL_TASK_ID"], errors="coerce")
    selected = manifest.loc[task_numbers == args.index]
    if len(selected) != 1:
        available = [int(x) for x in task_numbers.dropna()]
        raise RuntimeError(
            f"Index {args.index} is not present exactly once. Available: {available}"
        )

    row = selected.iloc[0]
    banner("STEP 08 - DIRECT SINGLE-INDEX MODE")
    print(f"Manifest : {manifest_file}")
    print(f"Index    : {args.index}")
    print(f"Study    : {row['STUDY_ACCESSION']}")
    print("Tissues  : ALL GTEx v11 tissues")
    print()
    print(
        "NOTE: the first run can scan several GB of GTEx data. On HPC use srun "
        "or submit the generated SLURM array rather than doing heavy work on a login node."
    )

    old_values = {
        key: os.environ.get(key)
        for key in [
            "SLURM_ARRAY_TASK_ID",
            "GWAS_QTL_MANIFEST",
            "SLURM_CPUS_PER_TASK",
            "STEP08_FORCE",
            "STEP08_REBUILD_CACHE",
        ]
    }

    try:
        os.environ["SLURM_ARRAY_TASK_ID"] = str(args.index)
        os.environ["GWAS_QTL_MANIFEST"] = str(manifest_file)
        os.environ["SLURM_CPUS_PER_TASK"] = str(args.cpus)
        if args.force:
            os.environ["STEP08_FORCE"] = "1"
        if args.rebuild_cache:
            os.environ["STEP08_REBUILD_CACHE"] = "1"
        worker_mode()
    finally:
        for key, value in old_values.items():
            if value is None:
                os.environ.pop(key, None)
            else:
                os.environ[key] = value


# =============================================================================
# MAIN
# =============================================================================

def main() -> None:
    if os.environ.get("SLURM_ARRAY_TASK_ID") and os.environ.get("GWAS_QTL_MANIFEST"):
        worker_mode()
        return

    args = arguments()
    if args.index is not None:
        direct_index_mode(args)
    else:
        planner_mode(args)


if __name__ == "__main__":
    main()
