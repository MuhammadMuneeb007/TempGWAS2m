def banner(text: str) -> None:
    print()
    print("=" * 104)
    print(text)
    print("=" * 104)


def normalize_text(value) -> str:
    text = str(value).lower()
    text = re.sub(r"[^a-z0-9]+", " ", text)
    text = re.sub(r"\s+", " ", text)
    return text.strip()


def slugify(value) -> str:
    return normalize_text(value).replace(" ", "_")


def canonical_ancestry(value: str) -> tuple[str, str]:
    key = normalize_text(value)
    if key not in ANCESTRY_ALIASES:
        raise ValueError(
            f"Unsupported ancestry: {value!r}. "
            "Use EUR, AFR, EAS, SAS, AMR or the corresponding full label."
        )
    return ANCESTRY_ALIASES[key]


def parse_walltime(value: str) -> int:
    text = str(value).strip()
    days = 0
    if "-" in text:
        day_text, text = text.split("-", 1)
        days = int(day_text)
    parts = text.split(":")
    if len(parts) != 3:
        raise ValueError("Walltime must be HH:MM:SS or D-HH:MM:SS")
    hours, minutes, seconds = map(int, parts)
    if days < 0 or hours < 0 or not 0 <= minutes < 60 or not 0 <= seconds < 60:
        raise ValueError("Invalid walltime")
    return days * 86400 + hours * 3600 + minutes * 60 + seconds


def validate_walltime(value: str) -> str:
    seconds = parse_walltime(value)
    if seconds <= 0:
        raise ValueError("Walltime must be greater than zero")
    if seconds > 86400:
        raise ValueError("Maximum allowed walltime is 24 hours")
    return value


def safe_read_json(path: Path) -> dict:
    if not path.exists() or path.stat().st_size == 0:
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return {}


def write_json(path: Path, payload: dict) -> None:
    path.write_text(
        json.dumps(payload, indent=2, default=str),
        encoding="utf-8",
    )


def first_existing(columns, candidates):
    lookup = {str(c).lower(): c for c in columns}
    for candidate in candidates:
        if candidate.lower() in lookup:
            return lookup[candidate.lower()]
    return None


def collapse(values) -> str:
    output = []
    for value in pd.Series(values).dropna().astype(str):
        for token in value.split(";"):
            token = token.strip()
            if token and token.lower() not in {"nan", "none", "."} and token not in output:
                output.append(token)
    return ";".join(output)


def safe_numeric_min(series):
    x = pd.to_numeric(series, errors="coerce").dropna()
    return float(x.min()) if not x.empty else np.nan


def safe_numeric_max_abs(series):
    x = pd.to_numeric(series, errors="coerce").dropna()
    return float(x.abs().max()) if not x.empty else np.nan


def sha256_strings(values) -> str:
    h = hashlib.sha256()
    for value in sorted(str(v) for v in values):
        h.update(value.encode("utf-8"))
        h.update(b"\n")
    return h.hexdigest()


def read_resource_env(root: Path) -> dict[str, str]:
    path = root / "resource_paths.env"
    result = {}
    if not path.exists():
        return result
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        if key.startswith("export "):
            key = key[7:].strip()
        value = value.strip().strip('"').strip("'")
        result[key] = value
    return result


