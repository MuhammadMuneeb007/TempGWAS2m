def map_targets_with_lookup(targets: pd.DataFrame, lookup_file: Path, chunk_size: int) -> pd.DataFrame:
    result = targets[[
        "GTEX_MATCH_KEY",
        "GTEX_CONSTRUCTED_VARIANT_ID",
        "CHR",
        "REFERENCE_POS",
        "REFERENCE_REF",
        "REFERENCE_ALT",
    ]].drop_duplicates().copy()

    result["GTEX_VARIANT_ID"] = result["GTEX_CONSTRUCTED_VARIANT_ID"]
    result["GTEX_SNP_ID"] = pd.Series([None] * len(result), index=result.index, dtype="object")
    result["GTEX_MAPPING_METHOD"] = "CONSTRUCTED_GRCH38"

    if not lookup_file.exists() or lookup_file.stat().st_size == 0:
        return result

    try:
        header = pd.read_csv(lookup_file, sep="\t", nrows=0, compression="infer")
    except Exception as error:
        print(f"WARNING: could not read GTEx lookup header: {error}")
        return result

    variant_col = first_existing(
        header.columns,
        ["variant_id", "variantId", "variant", "variant_id_b38"],
    )
    chr_col = first_existing(header.columns, ["chr", "chromosome", "chrom"])
    pos_col = first_existing(header.columns, ["pos", "position", "variant_pos"])
    ref_col = first_existing(header.columns, ["ref", "reference", "ref_allele"])
    alt_col = first_existing(header.columns, ["alt", "alternate", "alt_allele"])
    snp_col = first_existing(header.columns, ["snp_id", "snpId", "rs_id", "rsid"])

    # Many GTEx lookup tables contain only variant_id + rsID. In that case the
    # constructed b38 ID itself is already the exact lookup key.
    if variant_col is None:
        return result

    target_ids = set(result["GTEX_CONSTRUCTED_VARIANT_ID"].astype(str))
    matches = []

    usecols = [variant_col]
    if snp_col:
        usecols.append(snp_col)
    for c in (chr_col, pos_col, ref_col, alt_col):
        if c and c not in usecols:
            usecols.append(c)

    try:
        iterator = pd.read_csv(
            lookup_file,
            sep="\t",
            usecols=usecols,
            chunksize=chunk_size,
            compression="infer",
            low_memory=False,
        )

        for chunk in iterator:
            ids = chunk[variant_col].astype(str)
            hit = chunk.loc[ids.isin(target_ids)].copy()
            if not hit.empty:
                matches.append(hit)
    except Exception as error:
        print(f"WARNING: GTEx lookup scan failed; using constructed IDs: {error}")
        return result

    if not matches:
        return result

    mapped = pd.concat(matches, ignore_index=True)
    mapped = mapped.drop_duplicates(subset=[variant_col], keep="first")
    mapped = mapped.rename(columns={variant_col: "GTEX_VARIANT_ID_LOOKUP"})
    if snp_col:
        mapped = mapped.rename(columns={snp_col: "GTEX_SNP_ID_LOOKUP"})

    lookup_map = mapped.set_index("GTEX_VARIANT_ID_LOOKUP").to_dict(orient="index")

    for idx, row in result.iterrows():
        cid = str(row["GTEX_CONSTRUCTED_VARIANT_ID"])
        if cid in lookup_map:
            record = lookup_map[cid]
            result.at[idx, "GTEX_VARIANT_ID"] = cid
            result.at[idx, "GTEX_MAPPING_METHOD"] = "GTEX_V11_LOOKUP_EXACT"
            if "GTEX_SNP_ID_LOOKUP" in record:
                result.at[idx, "GTEX_SNP_ID"] = record.get("GTEX_SNP_ID_LOOKUP")

    return result


