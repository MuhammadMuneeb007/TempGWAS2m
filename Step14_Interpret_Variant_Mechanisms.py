def classify_mechanism(row, args):
    context = str(
        row.get(
            "VARIANT_CONTEXT",
            "",
        )
    )

    eqtl = row.get(
        "EQTL_LCLPP",
        np.nan,
    )

    sqtl = row.get(
        "SQTL_LCLPP",
        np.nan,
    )

    spliceai = row.get(
        "SPLICEAI_MAX_DS",
        np.nan,
    )

    pang_top5 = boolish(
        row.get(
            "PANGOLIN_TOP_5PCT",
            False,
        )
    )

    try:
        eqtl_support = (
            pd.notna(eqtl)
            and float(eqtl)
            >= args.eqtl_screen
        )

    except Exception:
        eqtl_support = False

    try:
        sqtl_support = (
            pd.notna(sqtl)
            and float(sqtl)
            >= args.sqtl_screen
        )

    except Exception:
        sqtl_support = False

    try:
        spliceai_support = (
            pd.notna(spliceai)
            and float(spliceai)
            >= args.spliceai_support
        )

    except Exception:
        spliceai_support = False

    canonical_splice = (
        "splice_acceptor_variant"
        in consequence_tokens(row)
        or
        "splice_donor_variant"
        in consequence_tokens(row)
    )

    ptv = (
        context
        ==
        "CODING_PTV_OR_CANONICAL_SPLICE"
        and
        not canonical_splice
    )

    missense = (
        context
        ==
        "CODING_MISSENSE_OR_PROTEIN_ALTERING"
    )

    expression = bool(
        eqtl_support
    )

    splicing = bool(
        canonical_splice
        or
        sqtl_support
        or
        spliceai_support
        or
        pang_top5
    )

    coding = bool(
        context.startswith(
            "CODING"
        )
    )

    mechanism_axes = []

    if ptv:
        mechanism_axes.append(
            "PROTEIN_TRUNCATION"
        )

    if missense:
        mechanism_axes.append(
            "PROTEIN_SEQUENCE"
        )

    if expression:
        mechanism_axes.append(
            "EXPRESSION"
        )

    if splicing:
        mechanism_axes.append(
            "SPLICING"
        )

    if (
        context
        in {
            "REGULATORY",
            "INTRONIC",
            "INTERGENIC",
            "UTR",
        }
        and
        expression
    ):
        mechanism_axes.append(
            "NONCODING_REGULATORY"
        )

    if context == "NONCODING_RNA":
        mechanism_axes.append(
            "NONCODING_RNA"
        )

    # Remove duplicates.
    mechanism_axes = list(
        dict.fromkeys(
            mechanism_axes
        )
    )

    if len(mechanism_axes) >= 2:
        mechanism = "MULTI_MECHANISM"

    elif ptv:
        mechanism = "CODING_PTV_CANDIDATE"

    elif missense:
        mechanism = "CODING_MISSENSE"

    elif canonical_splice:
        mechanism = "CANONICAL_SPLICE"

    elif splicing:
        mechanism = "SPLICING_MEDIATED"

    elif expression and not coding:
        mechanism = "EXPRESSION_MEDIATED_NONCODING"

    elif expression:
        mechanism = "EXPRESSION_MEDIATED"

    elif context == "NONCODING_RNA":
        mechanism = "NONCODING_RNA"

    elif context in {
        "REGULATORY",
        "INTRONIC",
        "INTERGENIC",
        "UTR",
    }:
        mechanism = "UNRESOLVED_NONCODING"

    elif context == "CODING_SYNONYMOUS":
        mechanism = "CODING_SYNONYMOUS_UNRESOLVED"

    elif coding:
        mechanism = "CODING_OTHER"

    else:
        mechanism = "UNRESOLVED"

    return pd.Series(
        {
            "MECHANISM_CLASS":
                mechanism,

            "MECHANISM_AXES":
                ";".join(
                    mechanism_axes
                ),

            "HAS_EXPRESSION_SUPPORT":
                expression,

            "HAS_SPLICING_SUPPORT":
                splicing,

            "HAS_PROTEIN_SEQUENCE_SUPPORT":
                (
                    ptv
                    or
                    missense
                ),
        }
    )


def followup_requirements(row, resource_status):
    available = {
        str(r["RESOURCE"]):
            bool(r["AVAILABLE"])
        for _, r in resource_status.iterrows()
    }

    needs = []

    context = str(
        row.get(
            "VARIANT_CONTEXT",
            "",
        )
    )

    if context == "CODING_PTV_OR_CANONICAL_SPLICE":
        needs.append(
            "LOFTEE_HIGH_CONFIDENCE_LOF"
        )

    if (
        context
        ==
        "CODING_MISSENSE_OR_PROTEIN_ALTERING"
        and
        not available.get(
            "ALPHAMISSENSE",
            False,
        )
    ):
        needs.append(
            "ALPHAMISSENSE"
        )

    if (
        context.startswith(
            "CODING"
        )
        and
        not available.get(
            "CLINVAR",
            False,
        )
    ):
        needs.append(
            "CLINVAR"
        )

    if (
        context.startswith(
            "CODING"
        )
        and
        not available.get(
            "CADD",
            False,
        )
    ):
        needs.append(
            "CADD"
        )

    if (
        row.get(
            "MECHANISM_CLASS",
            ""
        )
        in {
            "EXPRESSION_MEDIATED",
            "EXPRESSION_MEDIATED_NONCODING",
            "SPLICING_MEDIATED",
            "MULTI_MECHANISM",
        }
    ):
        needs.append(
            "FORMAL_COLOCALISATION_VALIDATION"
        )

    if not available.get(
        "MENDELIAN",
        False,
    ):
        needs.append(
            "MENDELIAN_GENE_DISEASE_RESOURCE"
        )

    if not available.get(
        "GENE_CONSTRAINT",
        False,
    ):
        needs.append(
            "GNOMAD_GENE_CONSTRAINT"
        )

    return ";".join(
        dict.fromkeys(
            needs
        )
    )


