def consequence_tokens(row):
    values = []

    for col in [
        "Consequence",
        "ALL_CONSEQUENCES",
    ]:
        value = row.get(col)

        if value is None:
            continue

        try:
            if pd.isna(value):
                continue
        except Exception:
            pass

        text = str(value)

        for token in re.split(r"[,;&]", text):
            token = token.strip().lower()

            if token:
                values.append(token)

    return set(values)


def classify_variant_context(row):
    terms = consequence_tokens(row)

    biotype = str(
        row.get("BIOTYPE", "")
    ).lower()

    functional = str(
        row.get(
            "FUNCTIONAL_CATEGORY",
            "",
        )
    ).upper()

    if terms & PTV_TERMS:
        return "CODING_PTV_OR_CANONICAL_SPLICE"

    if terms & MISSENSE_TERMS:
        return "CODING_MISSENSE_OR_PROTEIN_ALTERING"

    if terms & SYNONYMOUS_TERMS:
        return "CODING_SYNONYMOUS"

    if terms & SPLICE_TERMS:
        return "SPLICE_REGION"

    if terms & UTR_TERMS:
        return "UTR"

    if (
        functional == "NONCODING_RNA"
        or
        any(
            token.lower() in biotype
            for token in NONCODING_RNA_BIOTYPE_TOKENS
        )
    ):
        return "NONCODING_RNA"

    if (
        functional == "REGULATORY"
        or
        terms & {
            x.lower()
            for x in REGULATORY_TERMS
        }
    ):
        return "REGULATORY"

    if "intron_variant" in terms:
        return "INTRONIC"

    if "intergenic_variant" in terms:
        return "INTERGENIC"

    if functional == "CODING":
        return "CODING_OTHER"

    if functional == "SPLICING":
        return "SPLICING_OTHER"

    return "OTHER_OR_UNRESOLVED"


def protein_interpretation(row):
    context = row.get(
        "VARIANT_CONTEXT",
        "",
    )

    consequence = str(
        row.get(
            "Consequence",
            "",
        )
    )

    hgvsp = str(
        row.get(
            "HGVSp",
            "",
        )
    )

    aa = str(
        row.get(
            "Amino_acids",
            "",
        )
    )

    pos = str(
        row.get(
            "Protein_position",
            "",
        )
    )

    sift = str(
        row.get(
            "SIFT",
            "",
        )
    )

    polyphen = str(
        row.get(
            "PolyPhen",
            "",
        )
    )

    domain = str(
        row.get(
            "DOMAINS",
            "",
        )
    )

    parts = []

    if context == "CODING_PTV_OR_CANONICAL_SPLICE":
        parts.append(
            "protein-truncating/canonical-splice candidate"
        )

    elif context == "CODING_MISSENSE_OR_PROTEIN_ALTERING":
        parts.append(
            "protein-sequence-altering candidate"
        )

    elif context == "CODING_SYNONYMOUS":
        parts.append(
            "synonymous coding variant"
        )

    elif context.startswith("CODING"):
        parts.append(
            "coding variant"
        )

    else:
        return ""

    if consequence and consequence.lower() != "nan":
        parts.append(
            f"VEP={consequence}"
        )

    if hgvsp and hgvsp.lower() != "nan":
        parts.append(
            f"HGVSp={hgvsp}"
        )

    if aa and aa.lower() != "nan":
        parts.append(
            f"AA={aa}"
        )

    if pos and pos.lower() != "nan":
        parts.append(
            f"protein_position={pos}"
        )

    if sift and sift.lower() != "nan":
        parts.append(
            f"SIFT={sift}"
        )

    if polyphen and polyphen.lower() != "nan":
        parts.append(
            f"PolyPhen={polyphen}"
        )

    if domain and domain.lower() != "nan":
        parts.append(
            f"domain={domain}"
        )

    return " | ".join(parts)


