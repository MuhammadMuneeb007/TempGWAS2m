def resource_candidates(base, names):
    out = []

    for name in names:
        out.extend(
            [
                base / name,
                base / f"{name}.tsv",
                base / f"{name}.tsv.gz",
            ]
        )

    return out


def first_existing_file(paths):
    for path in paths:
        if (
            path.exists()
            and
            path.is_file()
            and
            path.stat().st_size > 0
        ):
            return path.resolve()

    return None


def load_variant_resource(path, resource_name):
    x = read_table(path)

    if x.empty:
        return x

    if "VARIANT_KEY" not in x.columns:
        chr_col = first_existing(
            x.columns,
            ["CHR", "CHROM", "CHROMOSOME"],
        )

        pos_col = first_existing(
            x.columns,
            ["POS", "POSITION"],
        )

        ref_col = first_existing(
            x.columns,
            ["REF", "REFERENCE", "REFERENCE_ALLELE"],
        )

        alt_col = first_existing(
            x.columns,
            ["ALT", "ALTERNATE", "ALTERNATE_ALLELE"],
        )

        if all(
            [chr_col, pos_col, ref_col, alt_col]
        ):
            x["VARIANT_KEY"] = [
                canonical_variant_from_parts(c, p, r, a)
                for c, p, r, a
                in zip(
                    x[chr_col],
                    x[pos_col],
                    x[ref_col],
                    x[alt_col],
                )
            ]

        else:
            raise RuntimeError(
                f"{resource_name} resource needs VARIANT_KEY "
                "or CHR/POS/REF/ALT columns: "
                f"{path}"
            )

    x["VARIANT_KEY"] = x[
        "VARIANT_KEY"
    ].map(canonical_variant)

    x = x[
        x["VARIANT_KEY"].astype(str).str.len() > 0
    ].copy()

    return x.drop_duplicates(
        "VARIANT_KEY",
        keep="first",
    )


def load_gene_resource(path):
    x = read_table(path)

    if x.empty:
        return x

    gene_id_col = first_existing(
        x.columns,
        ["GENE_ID", "GENE", "ENSEMBL_GENE_ID"],
    )

    symbol_col = first_existing(
        x.columns,
        ["SYMBOL", "GENE_SYMBOL"],
    )

    if gene_id_col:
        x["_GENE_ID_BASE"] = x[
            gene_id_col
        ].map(gene_base)

    else:
        x["_GENE_ID_BASE"] = ""

    if symbol_col:
        x["_GENE_SYMBOL"] = x[
            symbol_col
        ].fillna("").astype(str)

    else:
        x["_GENE_SYMBOL"] = ""

    return x


def load_optional_resources(paths, args):
    base = paths["RESOURCES"]

    explicit = {
        "CLINVAR":
            Path(args.clinvar).resolve()
            if args.clinvar
            else None,

        "ALPHAMISSENSE":
            Path(args.alphamissense).resolve()
            if args.alphamissense
            else None,

        "CADD":
            Path(args.cadd).resolve()
            if args.cadd
            else None,

        "GENE_CONSTRAINT":
            Path(args.gene_constraint).resolve()
            if args.gene_constraint
            else None,

        "MENDELIAN":
            Path(args.mendelian_resource).resolve()
            if args.mendelian_resource
            else None,
    }

    auto = {
        "CLINVAR":
            first_existing_file(
                resource_candidates(
                    base,
                    ["clinvar"],
                )
            ),

        "ALPHAMISSENSE":
            first_existing_file(
                resource_candidates(
                    base,
                    ["alphamissense"],
                )
            ),

        "CADD":
            first_existing_file(
                resource_candidates(
                    base,
                    ["cadd"],
                )
            ),

        "GENE_CONSTRAINT":
            first_existing_file(
                resource_candidates(
                    base,
                    [
                        "gene_constraint",
                        "gnomad_gene_constraint",
                    ],
                )
            ),

        "MENDELIAN":
            first_existing_file(
                resource_candidates(
                    base,
                    [
                        "mendelian_gene_disease",
                        "gene_disease",
                    ],
                )
            ),
    }

    status = []

    resources = {}

    for name in explicit:
        path = explicit[name] or auto[name]

        available = bool(
            path
            and
            path.exists()
            and
            path.stat().st_size > 0
        )

        status.append(
            {
                "RESOURCE":
                    name,

                "AVAILABLE":
                    available,

                "PATH":
                    str(path)
                    if path
                    else "",

                "INTERPRETATION":
                    (
                        "USED"
                        if available
                        else
                        "NOT_AVAILABLE_NOT_NEGATIVE_EVIDENCE"
                    ),
            }
        )

        if not available:
            resources[name] = pd.DataFrame()
            continue

        if name in {
            "CLINVAR",
            "ALPHAMISSENSE",
            "CADD",
        }:
            resources[name] = load_variant_resource(
                path,
                name,
            )

        else:
            resources[name] = load_gene_resource(
                path
            )

    return resources, pd.DataFrame(status)


