def process_study(
    paths,
    study,
    resources,
    resource_status,
    ot_status,
    args,
):
    vep = load_step07(
        paths,
        study,
    )

    if vep.empty:
        return pd.DataFrame()

    splice = load_step10(
        paths,
        study,
    )

    qtl = load_step11(
        paths,
        study,
    )

    eqtl = best_qtl_by_locus(
        qtl,
        "eQTL",
    )

    sqtl = best_qtl_by_locus(
        qtl,
        "sQTL",
    )

    x = vep.copy()

    x["STUDY_ID"] = study

    if not splice.empty:
        x = x.merge(
            splice,
            on="VARIANT_KEY",
            how="left",
            suffixes=(
                "",
                "_STEP10",
            ),
            validate="one_to_one",
        )

    if not eqtl.empty:
        x = x.merge(
            eqtl,
            on="LOCUS_ID",
            how="left",
            validate="many_to_one",
        )

    if not sqtl.empty:
        x = x.merge(
            sqtl,
            on="LOCUS_ID",
            how="left",
            validate="many_to_one",
        )

    if not ot_status.empty:
        local_ot = ot_status[
            ot_status[
                "STUDY_ID"
            ].astype(str)
            ==
            study
        ].copy()

        if not local_ot.empty:
            x = x.merge(
                local_ot.drop(
                    columns=[
                        "STUDY_ID",
                    ],
                    errors="ignore",
                ),
                on="LOCUS_ID",
                how="left",
                validate="many_to_one",
            )

    x = merge_optional_variant_resources(
        x,
        resources,
    )

    x["VARIANT_CONTEXT"] = x.apply(
        classify_variant_context,
        axis=1,
    )

    x["PROTEIN_INTERPRETATION"] = x.apply(
        protein_interpretation,
        axis=1,
    )

    # Exact top-shared variant matching.
    for prefix in [
        "EQTL",
        "SQTL",
    ]:
        col = (
            f"{prefix}_TOP_SHARED_VARIANT"
        )

        if col in x.columns:
            x[
                f"{prefix}_TOP_VARIANT_MATCH"
            ] = [
                canonical_variant(
                    v
                )
                ==
                canonical_variant(
                    q
                )
                and
                bool(
                    canonical_variant(
                        v
                    )
                )
                for v, q
                in zip(
                    x[
                        "VARIANT_KEY"
                    ],
                    x[
                        col
                    ],
                )
            ]

        else:
            x[
                f"{prefix}_TOP_VARIANT_MATCH"
            ] = False

    classification = x.apply(
        classify_mechanism,
        axis=1,
        args=args,
    )

    x = pd.concat(
        [
            x.reset_index(
                drop=True
            ),
            classification.reset_index(
                drop=True
            ),
        ],
        axis=1,
    )

    x = merge_gene_resources(
        x,
        resources,
    )

    x["FOLLOWUP_REQUIREMENTS"] = x.apply(
        lambda row:
            followup_requirements(
                row,
                resource_status,
            ),
        axis=1,
    )

    # Explicit evidence presence; absence of resource != negative evidence.
    x["CLINVAR_AVAILABLE_FOR_VARIANT"] = (
        x.get(
            "CLINVAR_SIGNIFICANCE",
            pd.Series(
                np.nan,
                index=x.index,
            ),
        )
        .notna()
    )

    x["ALPHAMISSENSE_AVAILABLE_FOR_VARIANT"] = (
        x.get(
            "ALPHAMISSENSE_SCORE",
            pd.Series(
                np.nan,
                index=x.index,
            ),
        )
        .notna()
    )

    x["CADD_AVAILABLE_FOR_VARIANT"] = (
        x.get(
            "CADD_PHRED",
            pd.Series(
                np.nan,
                index=x.index,
            ),
        )
        .notna()
    )

    # A descriptive evidence count only, NOT a causal score.
    evidence_columns = [
        "IN_95_CREDIBLE_SET",
        "HAS_EXPRESSION_SUPPORT",
        "HAS_SPLICING_SUPPORT",
        "HAS_PROTEIN_SEQUENCE_SUPPORT",
        "EQTL_TOP_VARIANT_MATCH",
        "SQTL_TOP_VARIANT_MATCH",
        "CLINVAR_AVAILABLE_FOR_VARIANT",
        "ALPHAMISSENSE_AVAILABLE_FOR_VARIANT",
        "CADD_AVAILABLE_FOR_VARIANT",
    ]

    x["N_DOCUMENTED_EVIDENCE_FLAGS"] = 0

    for col in evidence_columns:
        if col in x.columns:
            x[
                "N_DOCUMENTED_EVIDENCE_FLAGS"
            ] += x[
                col
            ].map(
                boolish
            ).astype(int)

    # Sort strongest fine-mapping first.
    x = x.sort_values(
        [
            "LOCUS_ID",
            "PIP",
        ],
        ascending=[
            True,
            False,
        ],
        kind="stable",
    )

    out_dir = (
        paths["OUT"]
        /
        study
    )

    out_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    x.to_csv(
        out_dir
        /
        f"{study}_mechanism_variants.tsv.gz",

        sep="\t",

        index=False,

        compression="gzip",
    )

    return x


