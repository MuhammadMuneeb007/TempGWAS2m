def best_qtl_by_locus(qtl, qtl_type):
    if qtl.empty:
        return pd.DataFrame()

    q = qtl[
        qtl.get(
            "QTL_TYPE",
            pd.Series("", index=qtl.index),
        )
        .fillna("")
        .astype(str)
        .str.lower()
        ==
        qtl_type.lower()
    ].copy()

    if q.empty:
        return pd.DataFrame()

    q = q.sort_values(
        [
            "LOCUS_ID",
            "LCLPP_MULTICAUSAL",
        ],
        ascending=[
            True,
            False,
        ],
    )

    q = q.drop_duplicates(
        "LOCUS_ID",
        keep="first",
    )

    prefix = (
        "EQTL"
        if qtl_type.lower() == "eqtl"
        else
        "SQTL"
    )

    rename = {
        "QTL_GENE_EFFECTIVE":
            f"{prefix}_GENE",

        "TISSUE":
            f"{prefix}_TISSUE",

        "LCLPP_MULTICAUSAL":
            f"{prefix}_LCLPP",

        "TOP_SHARED_VARIANT":
            f"{prefix}_TOP_SHARED_VARIANT",

        "QTL_PHENOTYPE":
            f"{prefix}_PHENOTYPE",
    }

    keep = [
        "LOCUS_ID",
        *[
            c
            for c in rename
            if c in q.columns
        ],
    ]

    return q[
        keep
    ].rename(
        columns=rename
    )


