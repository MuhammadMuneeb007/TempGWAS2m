def rename_resource_columns(
    x,
    resource,
):
    if x.empty:
        return x

    x = x.copy()

    renames = {}

    if resource == "CLINVAR":
        mappings = {
            "CLINVAR_SIGNIFICANCE":
                [
                    "CLINVAR_SIGNIFICANCE",
                    "CLNSIG",
                    "SIGNIFICANCE",
                ],

            "CLINVAR_CONDITION":
                [
                    "CLINVAR_CONDITION",
                    "CLNDN",
                    "CONDITION",
                ],

            "CLINVAR_REVIEW_STATUS":
                [
                    "CLINVAR_REVIEW_STATUS",
                    "CLNREVSTAT",
                    "REVIEW_STATUS",
                ],
        }

    elif resource == "ALPHAMISSENSE":
        mappings = {
            "ALPHAMISSENSE_SCORE":
                [
                    "ALPHAMISSENSE_SCORE",
                    "AM_SCORE",
                    "SCORE",
                ],

            "ALPHAMISSENSE_CLASS":
                [
                    "ALPHAMISSENSE_CLASS",
                    "AM_CLASS",
                    "CLASS",
                ],
        }

    elif resource == "CADD":
        mappings = {
            "CADD_PHRED":
                [
                    "CADD_PHRED",
                    "PHRED",
                    "CADD",
                ],
        }

    else:
        mappings = {}

    for target, candidates in mappings.items():
        source = first_existing(
            x.columns,
            candidates,
        )

        if source:
            renames[source] = target

    return x.rename(
        columns=renames
    )


def merge_optional_variant_resources(df, resources):
    out = df.copy()

    for resource in [
        "CLINVAR",
        "ALPHAMISSENSE",
        "CADD",
    ]:
        x = resources.get(
            resource,
            pd.DataFrame(),
        )

        if x.empty:
            continue

        x = rename_resource_columns(
            x,
            resource,
        )

        keep = [
            c
            for c in x.columns
            if (
                c == "VARIANT_KEY"
                or
                c.startswith(
                    resource
                )
                or
                (
                    resource == "CADD"
                    and c == "CADD_PHRED"
                )
            )
        ]

        x = x[
            keep
        ].drop_duplicates(
            "VARIANT_KEY",
            keep="first",
        )

        out = out.merge(
            x,
            on="VARIANT_KEY",
            how="left",
            validate="many_to_one",
        )

    return out


def choose_primary_gene(row):
    for col in [
        "SYMBOL",
        "Gene",
        "EQTL_GENE",
        "SQTL_GENE",
        "PANGOLIN_GENE",
        "SPLICEAI_GENE",
    ]:
        value = row.get(col)

        if value is None:
            continue

        try:
            if pd.isna(value):
                continue
        except Exception:
            pass

        x = str(value).strip()

        if x and x.lower() not in {
            "nan", "none", "."
        }:
            return gene_base(x)

    return ""


def merge_gene_resources(df, resources):
    out = df.copy()

    out["PRIMARY_GENE"] = out.apply(
        choose_primary_gene,
        axis=1,
    )

    # Constraint
    constraint = resources.get(
        "GENE_CONSTRAINT",
        pd.DataFrame(),
    )

    if not constraint.empty:
        loeuf = first_existing(
            constraint.columns,
            [
                "LOEUF",
                "oe_lof_upper",
            ],
        )

        pli = first_existing(
            constraint.columns,
            [
                "PLI",
                "pLI",
            ],
        )

        rows = []

        for _, row in constraint.iterrows():
            key = (
                gene_base(
                    row.get(
                        "_GENE_ID_BASE",
                        "",
                    )
                )
                or
                str(
                    row.get(
                        "_GENE_SYMBOL",
                        "",
                    )
                ).strip()
            )

            if not key:
                continue

            rows.append(
                {
                    "PRIMARY_GENE":
                        key,

                    "GNOMAD_LOEUF":
                        row.get(
                            loeuf,
                            np.nan,
                        )
                        if loeuf
                        else
                        np.nan,

                    "GNOMAD_PLI":
                        row.get(
                            pli,
                            np.nan,
                        )
                        if pli
                        else
                        np.nan,
                }
            )

        if rows:
            out = out.merge(
                pd.DataFrame(rows).drop_duplicates(
                    "PRIMARY_GENE",
                    keep="first",
                ),
                on="PRIMARY_GENE",
                how="left",
                validate="many_to_one",
            )

    # Mendelian
    mendelian = resources.get(
        "MENDELIAN",
        pd.DataFrame(),
    )

    if not mendelian.empty:
        disease_col = first_existing(
            mendelian.columns,
            [
                "MENDELIAN_DISEASE",
                "DISEASE",
                "CONDITION",
            ],
        )

        source_col = first_existing(
            mendelian.columns,
            [
                "MENDELIAN_SOURCE",
                "SOURCE",
            ],
        )

        evidence_col = first_existing(
            mendelian.columns,
            [
                "MENDELIAN_EVIDENCE",
                "EVIDENCE",
            ],
        )

        rows = []

        for _, row in mendelian.iterrows():
            key = (
                gene_base(
                    row.get(
                        "_GENE_ID_BASE",
                        "",
                    )
                )
                or
                str(
                    row.get(
                        "_GENE_SYMBOL",
                        "",
                    )
                ).strip()
            )

            if not key:
                continue

            rows.append(
                {
                    "PRIMARY_GENE":
                        key,

                    "MENDELIAN_DISEASE":
                        row.get(
                            disease_col,
                            "",
                        )
                        if disease_col
                        else "",

                    "MENDELIAN_SOURCE":
                        row.get(
                            source_col,
                            "",
                        )
                        if source_col
                        else "",

                    "MENDELIAN_EVIDENCE":
                        row.get(
                            evidence_col,
                            "",
                        )
                        if evidence_col
                        else "",
                }
            )

        if rows:
            m = pd.DataFrame(rows)

            m = (
                m.groupby(
                    "PRIMARY_GENE",
                    as_index=False,
                )
                .agg(
                    MENDELIAN_DISEASE=(
                        "MENDELIAN_DISEASE",
                        join_unique,
                    ),
                    MENDELIAN_SOURCE=(
                        "MENDELIAN_SOURCE",
                        join_unique,
                    ),
                    MENDELIAN_EVIDENCE=(
                        "MENDELIAN_EVIDENCE",
                        join_unique,
                    ),
                )
            )

            out = out.merge(
                m,
                on="PRIMARY_GENE",
                how="left",
                validate="many_to_one",
            )

    return out


