def load_step07(paths, study):
    path = (
        paths["S07"]
        /
        study
        /
        f"{study}_VEP_variant_summary.tsv"
    )

    x = read_table(path)

    if x.empty:
        return x

    required = [
        "LOCUS_ID",
        "CHR",
        "REFERENCE_POS",
        "REFERENCE_REF",
        "REFERENCE_ALT",
        "PIP",
    ]

    missing = [
        c
        for c in required
        if c not in x.columns
    ]

    if missing:
        raise RuntimeError(
            f"Step07 file missing columns {missing}: {path}"
        )

    x = x.copy()

    x["VARIANT_KEY"] = [
        canonical_variant_from_parts(c, p, r, a)
        for c, p, r, a
        in zip(
            x["CHR"],
            x["REFERENCE_POS"],
            x["REFERENCE_REF"],
            x["REFERENCE_ALT"],
        )
    ]

    x["PIP"] = safe_numeric(x["PIP"])

    if "IN_95_CREDIBLE_SET" in x.columns:
        x["IN_95_CREDIBLE_SET"] = x[
            "IN_95_CREDIBLE_SET"
        ].map(boolish)

    else:
        x["IN_95_CREDIBLE_SET"] = False

    return x


