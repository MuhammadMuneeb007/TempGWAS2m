def make_paths(root, phenotype, ancestry_label):
    p = slug(phenotype)
    a = slug(ancestry_label)

    return {
        "S06": root / "06_finemapping" / p / a,
        "S07": root / "07_annotation" / p / a,
        "S10": root / "10_pangolin" / p / a,
        "S11": root / "11_coloc" / p / a,
        "S13": root / "13_opentargets_detail" / p / a,
        "OUT": root / "14_mechanism" / p / a,
        "RESOURCES": root / "resources" / "mechanism",
    }


def discover_studies(paths):
    studies = set()

    for key in ["S06", "S07", "S10", "S11"]:
        base = paths[key]

        if not base.exists():
            continue

        for path in base.glob("GCST*"):
            if (
                path.is_dir()
                and
                re.fullmatch(r"GCST\d+", path.name)
            ):
                studies.add(path.name)

    return sorted(studies)


