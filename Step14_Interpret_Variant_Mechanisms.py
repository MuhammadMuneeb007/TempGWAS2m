def safe_numeric(value):
    return pd.to_numeric(value, errors="coerce")


def boolish(value):
    if isinstance(value, (bool, np.bool_)):
        return bool(value)

    if value is None:
        return False

    try:
        if pd.isna(value):
            return False
    except Exception:
        pass

    return str(value).strip().lower() in {
        "1", "true", "t", "yes", "y"
    }


def canonical_chr(value):
    if value is None:
        return ""

    try:
        if pd.isna(value):
            return ""
    except Exception:
        pass

    x = str(value).strip()
    x = re.sub(r"^chr", "", x, flags=re.I)

    if x.endswith(".0"):
        x = x[:-2]

    return x.upper()


def canonical_variant_from_parts(chrom, pos, ref, alt):
    chrom = canonical_chr(chrom)

    try:
        pos = str(int(float(pos)))
    except Exception:
        return ""

    ref = str(ref).strip().upper()
    alt = str(alt).strip().upper()

    if not chrom or not ref or not alt:
        return ""

    return f"{chrom}:{pos}:{ref}:{alt}"


def canonical_variant(value):
    if value is None:
        return ""

    try:
        if pd.isna(value):
            return ""
    except Exception:
        pass

    x = re.sub(r"^chr", "", str(value).strip(), flags=re.I)
    parts = re.split(r"[:_]", x)

    if len(parts) < 4:
        return ""

    return canonical_variant_from_parts(
        parts[0],
        parts[1],
        parts[2],
        parts[3],
    )


def gene_base(value):
    if value is None:
        return ""

    try:
        if pd.isna(value):
            return ""
    except Exception:
        pass

    x = str(value).strip()

    if x.lower() in {
        "", "nan", "none", "na", "null", "."
    }:
        return ""

    match = re.search(r"(ENSG\d+)", x, flags=re.I)

    return (
        match.group(1).upper()
        if match
        else x
    )


def first_existing(columns, candidates):
    lower = {
        str(c).lower(): c
        for c in columns
    }

    for candidate in candidates:
        if candidate in columns:
            return candidate

        if candidate.lower() in lower:
            return lower[candidate.lower()]

    return None


def join_unique(values, sep=";"):
    out = []

    for value in values:
        if value is None:
            continue

        try:
            if pd.isna(value):
                continue
        except Exception:
            pass

        for token in str(value).split(";"):
            token = token.strip()

            if token and token not in out:
                out.append(token)

    return sep.join(out)


def json_safe(obj):
    if isinstance(obj, np.integer):
        return int(obj)

    if isinstance(obj, np.floating):
        return None if np.isnan(obj) else float(obj)

    if isinstance(obj, np.bool_):
        return bool(obj)

    if isinstance(obj, np.ndarray):
        return obj.tolist()

    if isinstance(obj, Path):
        return str(obj)

    try:
        if pd.isna(obj):
            return None
    except Exception:
        pass

    raise TypeError(
        f"Object of type {type(obj).__name__} "
        "is not JSON serialisable"
    )


